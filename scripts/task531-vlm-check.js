let pass = 0, fail = 0;
const bad = [];
for (const [file, q, wants] of shots) {
    const p = path.join(DIR, file);
    if (!fs.existsSync(p)) {
        console.log('X ' + file + ' — нет файла');
        fail++;
        bad.push(file);
        continue;
    }
    process.stdout.write('? ' + file + ' … ');
    let ans = '';
    try {
        ans = vision(file, q);
    } catch (e) {
        ans = 'ОШИБКА: ' + e.message;
    }
    const text = String(ans);
    let ok = true;
    const missed = [];
    for (const key of Object.keys(wants)) {
        const re = new RegExp(key + '\\s*[:：]\\s*(да|нет)', 'i');
        const m = text.match(re);
        if (!m) { ok = false; missed.push(key + ':нет-ответа'); continue; }
        if (m[1].toLowerCase() !== wants[key]) {
            ok = false;
            missed.push(key + ':' + m[1]);
        }
    }
    if (ok) { pass++; console.log('OK'); }
    else {
        fail++; bad.push(file);
        console.log('X  [' + missed.join(', ') + ']');
        console.log('--- ' + file + ' ---\n' + text.slice(0, 700) + '\n');
    }
}

console.log('VLM ИТОГ: ' + pass + ' passed, ' + fail + ' failed' +
    (bad.length ? '  [' + bad.join(', ') + ']' : ''));
process.exit(fail ? 1 : 0);
