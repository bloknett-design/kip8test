#!/usr/bin/env python3
# -*- coding: utf-8 -*-
# Task 362: правки index.html (печатная форма графика работы):
#   1) список мероприятий в видах «сменный»/«дневной» — только
#      сотрудники ПЕЧАТАЕМЫХ строк (заявка: «при печати сменного
#      графика мероприятия должны быть указаны только для сменных
#      сотрудников, так же при печати графика дневного персонала»);
#      полный вид — без фильтра (как окно «Мероприятия», регресс 360);
#   2) коды мероприятий месяца — в перечень кодов (заявка: «не
#      отобразилось наименование кода проверки знаний ПЗ, хотя он
#      есть в мероприятиях у дневного сотрудника»): usedCodes
#      пополняется кодами из отфильтрованного списка мероприятий —
#      бейджи в ячейках печати строятся по «Инструктажам» без записей
#      сетки, сноска ссылается на перечень выше.
# Каждая замена — ровно один раз (assert).
import io

path = 'index.html'
src = io.open(path, encoding='utf-8').read()
orig = src

def rep(old, new, tag):
    global src
    n = src.count(old)
    assert n == 1, 'FAIL %s: найдено %d вхождений' % (tag, n)
    src = src.replace(old, new)
    print('OK %s' % tag)

# ---- 1. комментарий над printGrid (шапка блока печати) ----
rep(u'''        // Task 360 (заявка): ПОД шахматкой — список мероприятий
        // текущего месяца (один столбик: дата · код · тема · ФИО,
        // как в окне «Мероприятия»), ПОД ним — перечень кодов
        // ТОЛЬКО этого месяца с наименованиями (один столбик).''',
    u'''        // Task 360 (заявка): ПОД шахматкой — список мероприятий
        // текущего месяца (один столбик: дата · код · тема · ФИО,
        // как в окне «Мероприятия»), ПОД ним — перечень кодов
        // ТОЛЬКО этого месяца с наименованиями (один столбик).
        // Task 362 (заявка): в видах «сменный»/«дневной» список
        // мероприятий — только сотрудники ЭТОГО вида (как строки
        // шахматки); коды мероприятий месяца попадают в перечень
        // кодов (бейджи в ячейках печатаются из «Инструктажей»
        // без записей сетки).''',
    '1: шапка комментария printGrid')

# ---- 2. комментарий usedCodes ----
rep(u'''            // «.» и коды мероприятий (И/ОБ/ПЗ/ПР/*) — тоже коды
            // месяца: «.» виден в ячейках, коды мероприятий —
            // раскрываются в списке мероприятий выше''',
    u'''            // «.» и коды мероприятий (И/ОБ/ПЗ/ПР/*) — тоже коды
            // месяца: «.» виден в ячейках, коды мероприятий —
            // раскрываются в списке мероприятий выше. Task 362
            // (заявка: «не отобразилось наименование кода проверки
            // знаний ПЗ, хотя он есть в мероприятиях у дневного
            // сотрудника»): коды мероприятий добавляются в
            // usedCodes и из СПИСКА МЕРОПРИЯТИЙ месяца (см. цикл
            // evList ниже) — у дневного персонала мероприятие живёт
            // только в «Инструктажах», записи сетки нет, а бейдж в
            // ячейке печати ставится — перечень обязан объяснять
            // и его''',
    '2: комментарий usedCodes')

# ---- 3. фильтр мероприятий по виду (Task 362) ----
rep(u'''            var evList = [];
            var trs = this._TRAININGS || [];
            for (var ti = 0; ti < trs.length; ti++) {
                var tr = trs[ti];
                var trS = tr['дата_начала'];
                if (!trS) continue;
                var trE = tr['дата_окончания'] || trS;
                if (trE < mStart || trS > mEnd) continue;
                evList.push(tr);
            }''',
    u'''            var evList = [];
            var trs = this._TRAININGS || [];
            // Task 362 (заявка: «при печати сменного графика
            // мероприятия должны быть указаны только для сменных
            // сотрудников, так же при печати графика дневного
            // персонала»): в видах «сменный»/«дневной» в списке —
            // ТОЛЬКО мероприятия сотрудников ПЕЧАТАЕМЫХ строк
            // (viewEmps — те же строки, что и в шахматке выше:
            // фильтр вида + скрытие «Мастер КИПиА» у уровня min),
            // ровно те, чьи бейджи напечатаны в ячейках. Полный
            // вид — БЕЗ фильтра, как в окне «Мероприятия» тулбара
            // (регресс Task 360: все записи месяца подразделения)
            var viewTabs = {};
            for (var vi = 0; vi < viewEmps.length; vi++) {
                viewTabs[viewEmps[vi]['таб_номер']] = true;
            }
            var evByView = (this._view === 'shift' || this._view === 'day');
            for (var ti = 0; ti < trs.length; ti++) {
                var tr = trs[ti];
                var trS = tr['дата_начала'];
                if (!trS) continue;
                var trE = tr['дата_окончания'] || trS;
                if (trE < mStart || trS > mEnd) continue;
                if (evByView && !viewTabs[tr['таб_номер']]) continue;
                evList.push(tr);
            }''',
    '3: фильтр мероприятий по виду')

# ---- 4. коды мероприятий -> usedCodes (после сортировки evList) ----
rep(u'''            evList.sort(function(a, b) {
                return String(a['дата_начала']).localeCompare(String(b['дата_начала'])) ||
                       String(a['таб_номер']).localeCompare(String(b['таб_номер']));
            });
            // ФИО по таб. номеру (сотрудник мог быть удалён/в
            // архиве — показываем таб. номер)''',
    u'''            evList.sort(function(a, b) {
                return String(a['дата_начала']).localeCompare(String(b['дата_начала'])) ||
                       String(a['таб_номер']).localeCompare(String(b['таб_номер']));
            });
            // Task 362 (заявка: «не отобразилось наименование кода
            // проверки знаний ПЗ, хотя он есть в мероприятиях у
            // дневного сотрудника»): коды мероприятий отфильтрован-
            // ного списка тоже помечаются в usedCodes — бейджи в
            // ячейках печати строятся по «Инструктажам» БЕЗ записей
            // сетки, сноска листа ссылается на перечень выше; коды
            // событий сетки (статус-мероприятия) уже учтены в цикле
            // строк шахматки
            for (var eci = 0; eci < evList.length; eci++) {
                var evCd = (typeof this._trainingCodeOf === 'function')
                    ? this._trainingCodeOf(evList[eci]['тип']) : '';
                if (evCd) usedCodes[evCd] = true;
            }
            // ФИО по таб. номеру (сотрудник мог быть удалён/в
            // архиве — показываем таб. номер)''',
    '4: коды мероприятий в usedCodes')

assert src != orig, 'изменений нет'
io.open(path, 'w', encoding='utf-8').write(src)
print('index.html: 4 правки Task 362 применены')
