def main():
    import sys
    total = 0
    for path, repls in ADAPT.items():
        s = open(path, encoding='utf-8').read()
        for i, (old, new) in enumerate(repls, 1):
            cnt = s.count(old)
            if cnt != 1:
                print('ОШИБКА: %s якорь #%d найден %d раз' % (path, i, cnt))
                sys.exit(1)
            s = s.replace(old, new)
            total += 1
        open(path, 'w', encoding='utf-8').write(s)
        print('%s: %d правок' % (path, len(repls)))
    print('всего правок: %d' % total)


if __name__ == '__main__':
    main()
