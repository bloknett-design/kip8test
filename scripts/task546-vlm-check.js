let bad = 0;
for (const [file, prompt] of shots) {
    const p = path.join(DIR, file);
    if (!fs.existsSync(p)) { console.log('НЕТ ФАЙЛА: ' + file); bad++; continue; }
    process.stdout.write('== ' + file + ' ==\n');
    try {
        const answer = vision(file, prompt);
        console.log(answer);
    } catch (e) {
        console.log('ОШИБКА VLM: ' + e.message.slice(0, 200));
        bad++;
    }
    process.stdout.write('\n');
    // пауза против 429 (урок Task 544)
    Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, 6000);
}
