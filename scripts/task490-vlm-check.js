#!/usr/bin/env node
// scripts/task490-vlm-check.js — VLM-проверка скриншотов Task 490
// (паттерн task489-vlm-check.js; CLI `z-ai vision`).
// Ожидаем: мобильная страница «Датчики температуры» — кнопки-карточки
// по ДВЕ в строке; на кнопках ТС только градуировка и α (без «R₀»,
// «(Cu50)», «НСХ»); на кнопках ТП только «ТХА (K)»-стиль (без
// материалов электродов); ТХА (K) и ТХК (L) в одной строке; ТПР (B)
// во всю строку. Десктоп — полные карточки, порядок K, L первыми.
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const DIR = '/home/z/my-project/download/kip8test-task490';

function vision(file, prompt) {
    const out = execFileSync('z-ai', [
        'vision', '-p', prompt, '-i', path.join(DIR, file)
    ], { encoding: 'utf8', timeout: 120000, stdio: ['ignore', 'pipe', 'pipe'] });
    const m = out.match(/"content":\s*"((?:[^"\\]|\\.)*)"/);
    return m ? JSON.parse('"' + m[1] + '"') : out;
}

const shots = [
    ['a-mobile-rtd-pairs.png',
     'Это скриншот мобильного веб-приложения (тёмная тема, ширина 375). Открыт раздел «Датчики температуры» с группами «Термометры сопротивления» и «Термопары». Ответь строго по пунктам: (1) Сколько карточек-кнопок помещается в одной строке — одна или две? (2) Напиши, какие обозначения видны на первых двух карточках термометров (например 50М, 100М) и стоят ли они рядом в одной строке? (3) Есть ли на карточках термометров надписи вида «R₀ = 50 Ом», скобки «(Cu50)»/«(Pt100)» или строки «НСХ: −50…200 °C»? (4) Есть ли на карточках термометров строка температурного коэффициента, начинающаяся с «α»? (5) В группе «Термопары»: в одной ли строке кнопки «ТХА (K)» и «ТХК (L)»? (6) Есть ли на кнопках термопар материалы электродов («хромель-алюмель», «хромель-копель»)? (7) Кнопка «ТПР (B)» — во всю ширину строки или половину?'],
    ['d-mobile-light-pairs.png',
     'Это скриншот мобильного веб-приложения (СВЕТЛАЯ тема, ширина 375), раздел «Датчики температуры». Ответь строго по пунктам: (1) Карточки-кнопки идут по две в строке? (2) Текст на кнопках читаем — тёмный на светлом фоне (не белый-на-белом)? (3) Какие обозначения градуировок видны (50М, 100М, Pt100, ТХА (K), ТХК (L)…)? (4) Есть ли на кнопках длинные подписи «R₀», «НСХ» или названия материалов электродов?'],
    ['c-desktop-full-cards.png',
     'Это скриншот ДЕСКТОПНОЙ версии (1280px, тёмная тема) раздела «Датчики температуры». Ответь строго по пунктам: (1) Карточек в строке больше двух (сетка автозаполнения)? (2) Видны ли на карточках ПОЛНЫЕ подписи: «50М (Cu50)», «R₀ = 50 Ом», «НСХ: −50…200 °C», «хромель-алюмель»? (3) Первые две карточки термопар — «ТХА (K)» и «ТХК (L)»?']
];

let pass = 0, fail = 0;
for (const [file, prompt] of shots) {
    if (!fs.existsSync(path.join(DIR, file))) {
        console.log('нет файла ' + file); fail++; continue;
    }
    const txt = vision(file, prompt);
    console.log('=== ' + file + ' ===');
    console.log(String(txt).slice(0, 2000));
    console.log('');
    if (/две|двух|рядом/i.test(txt)) pass++;
    else fail++;
}
console.log('VLM: %d passed, %d failed', pass, fail);
if (fail) process.exit(1);
