# Task 392: адаптация тестов прошлых задач — строка «Работников на
# текущий момент»: ведущее число БЕЗ СКОБОК (заявка: «"(12) (2
# мастера…)" — 12 без скобок»). Формат «(N) (разбивка)» →
# «N (разбивка)». Затрагивает: test-task391.js (SRC-ассерт скобок +
# VM-строки), test-task389.js и test-task390.js (VM-строки).
# Каждый якорь проверяется на единственность в СВОЁМ файле.
import io, sys

def patch(path, repls):
    s = io.open(path, encoding='utf-8').read()
    for i, (old, new) in enumerate(repls):
        n = s.count(old)
        if n != 1:
            print('FAIL %s: якорь #%d найден %d раз: %r' % (path, i + 1, n, old[:60]))
            sys.exit(1)
    for (old, new) in repls:
        s = s.replace(old, new)
    io.open(path, 'w', encoding='utf-8').write(s)
    print('  OK %s: %d правок' % (path, len(repls)))

# --- test-task391.js: SRC-ассект скобок + VM-строки ---
patch('tests/test-task391.js', [
    # SRC: ассерт «'(' + totalN + ') ('» → ведущее число без скобок
    (r"""        assertTrue(fn.indexOf("'(' + totalN + ') ('") !== -1,
            'скобки подряд: (итог) (разбивка)');""",
     r"""        assertTrue(fn.indexOf("totalN + ' ('") !== -1,
            'Task 392: ведущее число БЕЗ скобок, разбивка — в скобках');"""),
    # VM: «(6) (2 мастера, 2 дневных, 2 сменных).» → «6 (…)»
    (r"""'Работников на текущий момент (6) (2 мастера, 2 дневных, 2 сменных).') !== -1,""",
     r"""'Работников на текущий момент 6 (2 мастера, 2 дневных, 2 сменных).') !== -1,"""),
    # VM: «(4) (1 мастер, 1 дневной, 2 сменных).» → «4 (…)»
    (r"""'Работников на текущий момент (4) (1 мастер, 1 дневной, 2 сменных).') !== -1,""",
     r"""'Работников на текущий момент 4 (1 мастер, 1 дневной, 2 сменных).') !== -1,"""),
    # VM: «(0) (0 мастеров…)» → «0 (…)»
    (r"""'Работников на текущий момент (0) (0 мастеров, 0 дневных, 0 сменных).') !== -1,""",
     r"""'Работников на текущий момент 0 (0 мастеров, 0 дневных, 0 сменных).') !== -1,"""),
    # VM: наличие «…момент (6)» → «…момент 6»
    (r"""body.indexOf('Работников на текущий момент (6)') !== -1,""",
     r"""body.indexOf('Работников на текущий момент 6') !== -1,"""),
])

