#!/usr/bin/env node
// scripts/task555-vlm-check.js — VLM-проверка скриншотов Task 555
// (паттерн task553-vlm-check.js; CLI `z-ai vision`).
// Заявка: краткое наименование пункта «Список_И_и_ПЗ» В НАЧАЛЕ
// каждой строки блока «Повторные инструктажи и периодическая
// проверка знаний» карточки работника — «более выраженным
// шрифтом (инструктажи - синим цветом, проверки знаний - красным,
// как цвет у их мини значков), а затем остальной текст более
// мелким шрифтом. И шрифт не должен тускнеть при отметке
// выполнения».
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const DIR = '/home/z/my-project/download/kip8test-task555';

function vision(file, prompt) {
    const out = execFileSync('z-ai', [
        'vision', '-p', prompt, '-i', path.join(DIR, file)
    ], { encoding: 'utf8', timeout: 120000, stdio: ['ignore', 'pipe', 'pipe'] });
    const m = out.match(/"content":\s*"((?:[^"\\]|\\.)*)"/);
    return m ? JSON.parse('"' + m[1] + '"') : out;
}

const SHORT_DARK = 'Это страница «Работники» раздела «Табель учёта рабочего времени» (тёмная тема), карточка работника Иванова. Блок «Повторные инструктажи и периодическая проверка знаний · 2026»: каждая строка НАЧИНАЕТСЯ кратким наименованием пункта (выделено жирным и цветом), затем идёт полное название мельче, дата и примечание. Ответь строго по пунктам: (1) Строка с датой 15.03.2026 начинается кратким «ОТ-РИ» СИНИМ жирным шрифтом, затем полное «Повторный инструктаж по рабочим инструкциям» мельче и примечание «протокол № 12, ведёт Иванов А.А.»? (2) Строка с датой 20.05.2026 начинается кратким «ПЗ-1000В» КРАСНЫМ жирным? (3) Строка с датой 10.02.2026 — краткое «9-ОГЭ» синим, у строки ЗЕЛЁНАЯ галочка слева от кнопок, при этом её текст читаем НОРМАЛЬНО (не тусклый, не серый)? (4) Строки с «Проверка знаний по промышленной безопасности» (05.04.2026) и «Аварийный внеплановый инструктаж» (02.09.2026) НЕ имеют цветного краткого префикса в начале? (5) Визуальные дефекты (наложение, обрезка, разъехавшаяся вёрстка) есть?';
const SHORT_DONE = 'Та же карточка работника Иванова (тёмная тема) после отметки выполнения галочкой строки с датой 15.03.2026. Ответь строго по пунктам: (1) У строки 15.03.2026 появилась ЗЕЛЁНАЯ галочка (✓) в правой колонке? (2) Текст строки (краткое «ОТ-РИ» синим + полное название + дата + примечание) остался НОРМАЛЬНО читаемым — НЕ тускнеет, не сереет после отметки? (3) Другие строки не сломались? (4) Визуальные дефекты есть?';
const SHORT_LIGHT = 'Та же страница «Работники» в СВЕТЛОЙ теме, карточка Иванова, блок «Повторные инструктажи и периодическая проверка знаний · 2026». Ответь строго по пунктам: (1) Краткие наименования в начале строк («ОТ-РИ», «9-ОГЭ») — СИНИЕ на светлом фоне и хорошо читаются? (2) Краткое «ПЗ-1000В» — КРАСНОЕ и читается? (3) Остальной текст строк (полные названия, даты, примечание курсивом) читаем и мельче кратких наименований? (4) Визуальные дефекты есть?';

const shots = [
    ['01-workers-017-short-dark.png', SHORT_DARK],
    ['02-workers-017-short-after-done.png', SHORT_DONE],
    ['03-workers-017-short-light.png', SHORT_LIGHT]
];

const results = {};
shots.forEach(function(pair) {
    const txt = vision(pair[0], pair[1]);
    results[pair[0]] = txt;
    console.log('=== ' + pair[0] + ' ===');
    console.log(txt.slice(0, 800));
});

function low(f) { return String(results[f] || '').toLowerCase(); }
const DARK = '01-workers-017-short-dark.png';
const DONE = '02-workers-017-short-after-done.png';
const LIGHT = '03-workers-017-short-light.png';
const checks = [
    ['A: тёмная — «ОТ-РИ» синим жирным в начале строки 15.03',
     /от-ри/.test(low(DARK)) && /син/.test(low(DARK))],
    ['A: тёмная — «ПЗ-1000В» красным',
     /пз-1000в/.test(low(DARK)) && /красн/.test(low(DARK))],
    ['A: тёмная — примечание на месте в остальном тексте',
     low(DARK).indexOf('протокол № 12') !== -1],
    ['A: тёмная — строки без сокращения не имеют цветного префикса',
     /(не имеют|без)[^.]{0,60}(префикс|кратк)|нет[^.]{0,40}цветного/.test(low(DARK))],
    ['B: после отметки — галочка зелёная, текст не тускнеет',
     /зел[ёе]н/.test(low(DONE)) &&
     (/(не тускне|не тускл|не сере|нормальн[^.]{0,30}читаем)/.test(low(DONE)))],
    ['C: светлая — синие краткие читаемы',
     /син/.test(low(LIGHT)) && /(чита|видн|хорошо)/.test(low(LIGHT))],
    ['C: светлая — красное краткое читается',
     /красн/.test(low(LIGHT))],
    ['санитар: affirmed визуальные дефекты (все кадры)',
     shots.every(function(p) {
         return !/(есть|присутствуют?)[^.]{0,40}(дефект|наложен|обрезк|перекрыв)/i.test(
             results[p[0]] || '');
     })]
];

let ok = 0;
checks.forEach(function(c) {
    console.log((c[1] ? '  + ' : '  X ') + c[0]);
    if (c[1]) ok++;
});
console.log('\nVLM-итог: ' + ok + '/' + checks.length);
process.exit(ok === checks.length ? 0 : 1);
