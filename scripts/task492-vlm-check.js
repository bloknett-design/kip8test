#!/usr/bin/env node
// scripts/task492-vlm-check.js — VLM-проверка скриншотов Task 492
// (паттерн task490-vlm-check.js; CLI `z-ai vision`).
// Ожидаем: мобильная страница «Датчики температуры» — ВНИЗУ экрана
// фиксированный бар «Все / Избранные» (как в расходомерах), верхних
// табов нет; карточки с избранным выделены рамкой/выступом, шрифт у
// всех одинаковый; десктоп — табы сверху, бара внизу нет.
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const DIR = '/home/z/my-project/download/kip8test-task492';

function vision(file, prompt) {
    const out = execFileSync('z-ai', [
        'vision', '-p', prompt, '-i', path.join(DIR, file)
    ], { encoding: 'utf8', timeout: 120000, stdio: ['ignore', 'pipe', 'pipe'] });
    const m = out.match(/"content":\s*"((?:[^"\\]|\\.)*)"/);
    return m ? JSON.parse('"' + m[1] + '"') : out;
}

const shots = [
    ['a-mobile-empty-fav.png',
     'Это скриншот мобильного веб-приложения (тёмная тема, 375px). Раздел «Датчики температуры», вкладка «Избранные» пуста. Ответь строго по пунктам: (1) Есть ли ВНИЗУ экрана закреплённая панель с двумя кнопками «Все» и «Избранные» (крупный текст, счётчики)? (2) Кнопки этой панели примерно равной ширины, каждая около половины экрана? (3) Есть ли тонкая вертикальная линия-разделитель между кнопками? (4) Виден ли текст «Нет избранных датчиков»? (5) Есть ли над группой «Термометры сопротивления» небольшие переключатели «Все/Избранные» (компактная капсула)? — их быть НЕ должно. (6) Не перекрывает ли нижняя панель карточки или сообщение?'],
    ['b-mobile-fav-feat.png',
     'Это скриншот мобильного веб-приложения (тёмная тема, 375px), раздел «Датчики температуры», вкладка «Все». Ответь строго по пунктам: (1) Карточки-кнопки идут по две в строке? (2) РОВНО ОДНА карточка визуально выделена — более толстая синяя рамка, градиент фона и тень, будто «выступает» над остальными? (3) Какая это карточка (обозначение)? (4) На выделенной карточке есть звёздочка (закрашенная) в правом верхнем углу? (5) Размер шрифта обозначений (50М, 100М…) на ВЫДЕЛЕННОЙ и обычных карточках одинаковый? (6) Внизу экрана панель «Все 17 / Избранные 1»?'],
    ['c-mobile-light-fav-feat.png',
     'Это скриншот мобильного веб-приложения (СВЕТЛАЯ тема, 375px), раздел «Датчики температуры». Ответь строго по пунктам: (1) Внизу экрана панель с кнопками «Все / Избранные», активная «Избранные»? (2) Текст кнопок читаем (тёмно-синий на светлом фоне, не блёклый)? (3) Единственная карточка выделена рамкой и выглядит «приподнятой» (тень/градиент)? (4) Панель внизу не перекрывает карточку — между ними зазор?'],
    ['d-desktop-top-tabs.png',
     'Это скриншот ДЕСКТОПНОЙ версии (1280px, тёмная тема) раздела «Датчики температуры». Ответь строго по пунктам: (1) Переключатель «Все / Избранные» находится ВВЕРХУ списка (компактная капсула над «Термометры сопротивления»)? (2) Есть ли ВНИЗУ экрана закреплённая панель с крупными кнопками «Все / Избранные»? — её быть НЕ должно. (3) Карточки полные: видны «(Cu50)», «R₀ = 50 Ом», «НСХ»? (4) Карточки в строке больше двух?']
];

let pass = 0, fail = 0;
for (const [file, prompt] of shots) {
    if (!fs.existsSync(path.join(DIR, file))) {
        console.log('нет файла ' + file); fail++; continue;
    }
    const txt = vision(file, prompt);
    console.log('=== ' + file + ' ===');
    console.log(String(txt).slice(0, 2200));
    console.log('');
    if (/да|есть|одна|одинак/i.test(txt)) pass++;
    else fail++;
}
console.log('VLM: %d passed, %d failed', pass, fail);
if (fail) process.exit(1);
