edits = []

def edit(old, new, label):
    global src
    i = src.find(old)
    if i == -1:
        print('FAIL not found: ' + label); sys.exit(1)
    if src.find(old, i + 1) != -1:
        print('FAIL dup: ' + label); sys.exit(1)
    src = src[:i] + new + src[i + len(old):]
    edits.append(label)

