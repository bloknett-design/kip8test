function low(f) { return String(results[f] || '').toLowerCase(); }
function has(f, re) { return re.test(low(f)); }
function quoted(f, s) { return low(f).indexOf(s) !== -1; }
// Дефекты: только УТВЕРЖДЕНИЯ о наличии. Окно ЗАХВАТЫВАЕТ и хвост
