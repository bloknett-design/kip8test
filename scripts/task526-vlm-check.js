// накладываются» — это ОТРИЦАНИЯ, не дефект (уроки Task 523-525:
// VLM часто отвечает «дефектов нет», эхо нельзя матчить наивно).
function noDefects(f) {
    // Ручной скан вхождений (не regex global): глобальный regex
    // «съедает» контекст первого (отрицательного) вхождения, и второе
    // вхождение того же слова теряет стоящее перед ним «без/нет»
    // (урок Task 526: «(без разрывов), стрелки…» после матча «Дефектов
    // нет…»). Окно широкое (—34/+70): отрицание может стоять и ПОСЛЕ
    // перечисления («Видимых дефектов (искажений, артефактов…) нет»),
    // и на другой строке («не\nвылезает»).
    const raw = results[f] || '';
    const lowRaw = raw.toLowerCase();
    const words = ['разрыв', 'смещён', 'смещен', 'наложе', 'нечитаем',
                   'вылез', 'обрезан', 'не помеща', 'дефект', 'искаж'];
    const real = [];
    words.forEach(function (w) {
        let i = -1;
        while ((i = lowRaw.indexOf(w, i + 1)) !== -1) {
            const win = raw.slice(Math.max(0, i - 34), Math.min(raw.length, i + 70));
            if (!/(^|[^а-яё])(нет|без|не|отсутств|незамеч|не обнаруж|цел(ая|ые|ь))[^а-яё]/i.test(win)) {
                real.push(win.replace(/[\n\r]+/g, ' '));
            }
        }
    });
    if (real.length) console.log('    [дефект-фраза] ' + real[0]);
    return real.length === 0;
}

