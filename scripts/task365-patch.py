#!/usr/bin/env python3
# -*- coding: utf-8 -*-
# Task 365 (kip8test): заявка пользователя (с поправкой):
#   1) «В разделе Расходомеры хозрасчётные, в Хозрасчёте №12 период
#      указан еженедельно, но фактически нужно ежедневно, в
#      соответствии с формой ввода данных» — период №12 нормализуем
#      на клиенте (таблица hozraschet_meters в Google Sheets хранит
#      «Еженедельно»; записать туда из песочницы нельзя) + правим
#      fallback data/flowmeters.json;
#   2) «...красным должно быть с шести утра новых суток от суток
#      ввода данных, пока не введут новые данные, а не ровно час» —
#      поведение уже реализовано Task 357 (_isOverdue: красный с 6:00
#      следующих суток держится до ввода новых данных); закрепляем
#      поправку в комментариях логики/CSS (чтобы часовое окно
#      6:00–7:00 никто не «дореализовал») и в тестах.
# Правки index.html: _normalizeMeters + применение в 3 точках
# наполнения _METERS (fallback / кэш / сервер) + 2 комментария.
# Правка data/flowmeters.json: №12 «Еженедельно» → «Ежедневно».
# Запуск из корня репо kip8test.
import io
import json
import sys

PATH = 'index.html'
src = io.open(PATH, encoding='utf-8').read()
orig = src

def rep(old, new, what, count=1):
    global src
    n = src.count(old)
    assert n == count, '(%s) найдено %d вхождений, ожидалось %d' % (what, n, count)
    src = src.replace(old, new, count)
    print('OK: %s' % what)

# ============================================================
# 1. Хелпер _normalizeMeters — после _persistData, перед _fmtNum
# ============================================================
REP_NORMALIZE = '''        },

        // Task 365: нормализация периода расходомеров на клиенте.
        // Заявка: «в Хозрасчёте №12 период указан еженедельно, но
        // фактически нужно ежедневно, в соответствии с формой ввода
        // данных» — таблица hozрасчётов (Google Sheets, лист
        // hozraschet_meters) хранит устаревший «Еженедельно», а ввод
        // по №12 суточный (единое поле «Дата за предыдущие сутки»,
        // как у всех не-№1). Нормализуем период при ЛЮБОМ источнике
        // данных (сервер / кэш localStorage / fallback-json), чтобы
        // бейдж «Ежедневно», логика «пора вводить» (_isOverdue) и
        // суточная форма ввода совпадали. Когда период в таблице
        // станет «Ежедневно» — нормализация ничего не изменит
        // (идемпотентна).
        _normalizeMeters: function(meters) {
            if (!Array.isArray(meters)) return meters;
            for (var i = 0; i < meters.length; i++) {
                var nm = meters[i];
                if (nm && nm.id === 12 && nm.period !== 'Ежедневно') {
                    nm.period = 'Ежедневно';
                }
            }
            return meters;
        },

        // Форматирование числа с разделителями'''

rep('''        },

        // Форматирование числа с разделителями''',
    REP_NORMALIZE,
    'хелпер _normalizeMeters вставлен после _persistData')

# ============================================================
# 2. Точка наполнения: _loadFallback (data/flowmeters.json)
# ============================================================
rep('''                            if (!self._loaded) {
                                self._METERS = data.meters;
                            }''',
    '''                            if (!self._loaded) {
                                self._METERS = self._normalizeMeters(data.meters);
                            }''',
    '_loadFallback: нормализация fallback-данных')

# ============================================================
# 3. Точка наполнения: _restoreCache (localStorage)
# ============================================================
rep('''                        if (!this._loaded) {
                            this._METERS = cached.meters;
                            this._loaded = true;
                        }''',
    '''                        if (!this._loaded) {
                            this._METERS = this._normalizeMeters(cached.meters);
                            this._loaded = true;
                        }''',
    '_restoreCache: нормализация кэша localStorage')

# ============================================================
# 4. Точка наполнения: load() (сервер flowmeter.list)
# ============================================================
rep('''                if (data && Array.isArray(data.meters)) {
                    self._METERS = data.meters;
                    self._loaded = true;''',
    '''                if (data && Array.isArray(data.meters)) {
                    self._METERS = self._normalizeMeters(data.meters);
                    self._loaded = true;''',
    'load(): нормализация серверных данных')

# ============================================================
# 5. Комментарий блока _isOverdue — поправка заявки «не час»
# ============================================================
rep('''        //   Ежедневно   — с 6:00 текущих суток нет показаний за
        //                 предыдущие сутки; после ввода и сохранения
        //                 цвет зелёный до 6:00 следующих суток
        //                 (цикл ввода начинается в 6:00: до 6:00
        //                 действует цикл прошлых суток — «предыдущие
        //                 сутки» для него ещё старше на день).''',
    '''        //   Ежедневно   — с 6:00 текущих суток нет показаний за
        //                 предыдущие сутки; после ввода и сохранения
        //                 цвет зелёный до 6:00 следующих суток
        //                 (цикл ввода начинается в 6:00: до 6:00
        //                 действует цикл прошлых суток — «предыдущие
        //                 сутки» для него ещё старше на день).
        //   Task 365 (поправка заявки): красный «Ежедневно»
        //   стартует в 6:00 НОВЫХ суток — следующих за сутками
        //   ввода данных — и ДЕРЖИТСЯ, пока не введут новые данные;
        //   часового окна 6:00–7:00 НЕТ (первоначальная
        //   формулировка «ровно час» отменена поправкой
        //   пользователя: зелёный возвращается только вместе
        //   с новыми показаниями).''',
    'комментарий _isOverdue: поправка Task 365 «не час»')

# ============================================================
# 6. Комментарий CSS — поправка заявки «не час»
# ============================================================
rep('''       Task 359: красный ЯРЧЕ + шрифт крупнее (16px/700 → 18px/800) —
       значение лучше притягивает взгляд (замечание пользователя). */''',
    '''       Task 359: красный ЯРЧЕ + шрифт крупнее (16px/700 → 18px/800) —
       значение лучше притягивает взгляд (замечание пользователя).
       Task 365 (поправка заявки): красный — НЕ час: с 6:00 новых
       суток (следующих за сутками ввода данных) показания держатся
       красными, пока не введут новые данные; окна 6:00–7:00 нет. */''',
    'комментарий CSS .flow-summary-val-due: поправка Task 365')

assert src != orig, 'index.html не изменился'
io.open(PATH, 'w', encoding='utf-8').write(src)
print('index.html: 6 правок записано')

# ============================================================
# 7. data/flowmeters.json — №12 «Еженедельно» → «Ежедневно»
# ============================================================
JPATH = 'data/flowmeters.json'
data = json.load(io.open(JPATH, encoding='utf-8'))
m12 = None
for m in data['meters']:
    if m.get('id') == 12:
        m12 = m
        break
assert m12 is not None, 'flowmeters.json: расходомер id=12 не найден'
assert m12['period'] == 'Еженедельно', 'flowmeters.json: у №12 неожиданный период %r' % m12['period']
m12['period'] = 'Ежедневно'
with io.open(JPATH, 'w', encoding='utf-8') as f:
    json.dump(data, f, ensure_ascii=False, indent=2)
    f.write('\n')
print('data/flowmeters.json: №12 период «Еженедельно» → «Ежедневно»')
print('ГОТОВО: Task 365 — правки применены')
