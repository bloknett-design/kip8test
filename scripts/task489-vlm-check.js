#!/usr/bin/env node
// scripts/task489-vlm-check.js — VLM-проверка скриншотов Task 489
// (паттерн task488-vlm-check.js; CLI `z-ai vision`).
// Ожидаем: карточка работника — шапка с ПОЛНЫМ ФИО
// («Хадасевич Александр Сергеевич · таб. № 2741») и «Дата рождения»
// (15.03.1985) ПОСЛЕ «Комментария» (конец списка профиля);
// шторка «Правка работника» — поля Фамилия/Имя/Отчество и «Дата
// рождения», а НЕ единое поле «ФИО»; шахматка — строки с КРАТКИМ
// ФИО («Хадасевич А. С.»).
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const DIR = '/home/z/my-project/download/kip8test-task489';

function vision(file, prompt) {
    const out = execFileSync('z-ai', [
        'vision', '-p', prompt, '-i', path.join(DIR, file)
    ], { encoding: 'utf8', timeout: 120000, stdio: ['ignore', 'pipe', 'pipe'] });
    const m = out.match(/"content":\s*"((?:[^"\\]|\\.)*)"/);
    return m ? JSON.parse('"' + m[1] + '"') : out;
}

const shots = [
    ['b-card-full-fio-birth.png',
     'Это скриншот веб-приложения табеля (тёмная тема): страница «Работники», карточка работника с блоками профиля. Ответь строго по пунктам: (1) Какой текст в заголовке-шапке блока профиля (ФИО и табельный номер) — приведи дословно. (2) Есть ли в списке профиля строка «Дата рождения» и какое у неё значение? (3) «Дата рождения» стоит после строк «Режим работы», «Должность», «Группа допуска», «Дата приёма» — то есть в конце списка? (4) ФИО в шапке — полное из трёх слов (фамилия имя отчество) или сокращённое с инициалами?'],
    ['c-edit-form-parts.png',
     'Это скриншот веб-приложения табеля (тёмная тема): шторка-форма «Правка работника». Ответь строго по пунктам: (1) Есть ли в форме ОТДЕЛЬНЫЕ поля «Фамилия», «Имя», «Отчество»? (2) Есть ли поле «Дата рождения» (ввод даты)? (3) Есть ли ЕДИНОЕ поле с подписью «ФИО» (одно текстовое поле на всё имя)? (4) Какие значения заполнены в полях Фамилия/Имя/Отчество?'],
    ['a-grid-short-fio.png',
     'Это скриншот веб-приложения табеля (тёмная тема): шахматка графика работы, колонка сотрудников слева. Ответь строго: (1) Как показываются имена работников в колонке «Сотрудник» — полностью (три слова) или сокращённо с инициалами? (2) Приведи примеры видимых ФИО. (3) Есть ли где-то на экране полное ФИО из трёх слов?']
];

let pass = 0, fail = 0;
for (const [file, prompt] of shots) {
    if (!fs.existsSync(path.join(DIR, file))) {
        console.log('нет файла ' + file); fail++; continue;
    }
    const txt = vision(file, prompt);
    console.log('=== ' + file + ' ===');
    console.log(String(txt).slice(0, 1400));
    console.log('');
    if (/Хадасевич|Фамилия|А\. С\./.test(txt)) pass++;
    else fail++;
}
console.log('VLM: %d passed, %d failed', pass, fail);
if (fail) process.exit(1);
