#!/usr/bin/env node
// scripts/task525-vlm-check.js — VLM-проверка скриншотов Task 525
// (паттерн task524-vlm-check.js; CLI `z-ai vision`).
// Заявка: на кнопке инструкции СО 153-34.03.603-2003 в разделе
// Библиотека/Электробезопасность — строка «Отменена — приказ
// Минэнерго России от 01.12.2023 № 1105» (красная, обе темы).
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const DIR = '/home/z/my-project/download/kip8test-task525';

function vision(file, prompt) {
    const out = execFileSync('z-ai', [
        'vision', '-p', prompt, '-i', path.join(DIR, file)
    ], { encoding: 'utf8', timeout: 120000, stdio: ['ignore', 'pipe', 'pipe'] });
    const m = out.match(/"content":\s*"((?:[^"\\]|\\.)*)"/);
    return m ? JSON.parse('"' + m[1] + '"') : out;
}

const CANCELLED = 'Отменена — приказ Минэнерго России от 01.12.2023 № 1105';

const shots = [
    ['desktop-dark-so153-button.png',
     'Это кнопка «Инструкция СО 153-34.03.603-2003» в разделе «Электробезопасность» библиотеки настольного веб-приложения, тёмная тема. На кнопке: заголовок, серая подпись «Применение и испытание средств защиты…» и КРАСНАЯ строка статуса отмены. Ответь строго по пунктам: (1) Заголовок кнопки — «Инструкция СО 153-34.03.603-2003»? (2) Процитируй ДОСЛОВНО, буква в букву, КРАСНУЮ строку ЦЕЛИКОМ от начала до конца. (3) Эта строка выделена красным цветом? (4) Есть ли визуальные дефекты (наложение текста, обрезка, разъехавшаяся вёрстка)?'],
    ['desktop-light-so153-button.png',
     'Это раздел «Электробезопасность» в светлой теме: сетка из кнопок-плиток (ПУЭ, ПТЭЭП, ПОТЭЭ, Инструкция СО 153-34.03.603-2003, Дополнительно). Ответь строго по пунктам: (1) На кнопке «Инструкция СО 153-34.03.603-2003» есть строка, начинающаяся словом «Отменена»? Процитируй её ДОСЛОВНО ЦЕЛИКОМ. (2) Эта строка красного цвета? (3) У СОСЕДНИХ кнопок (ПУЭ, ПТЭЭП, ПОТЭЭ, Дополнительно) такой красной строки «Отменена…» НЕТ? (4) Есть ли визуальные дефекты?'],
    ['mobile-dark-so153-button.png',
     'Это мобильная версия (узкий экран) раздела «Электробезопасность», тёмная тема: список широких кнопок. Найди кнопку «Инструкция СО 153-34.03.603-2003». Ответь строго по пунктам: (1) Процитируй ДОСЛОВНО КРАСНУЮ строку на этой кнопке ЦЕЛИКОМ. (2) Строка читаема полностью, не обрезана краем экрана? (3) Есть ли визуальные дефекты?']
];

const results = {};
let pass = 0, fail = 0;
shots.forEach(function(pair) {
    const txt = vision(pair[0], pair[1]);
    results[pair[0]] = txt;
    console.log('=== ' + pair[0] + ' ===');
    console.log(txt.slice(0, 900));
});

function low(f) { return String(results[f] || '').toLowerCase(); }

// Дословная цитата строки отмены: ключевые части (допускаем вариацию
// тире/пробелов при цитировании, но дата/номер/ведомство обязательны)
function quotedCancelled(f) {
    const a = low(f);
    return a.indexOf('отменена') !== -1 &&
           /минэнерго россии|минэнерго/.test(a) &&
           /01\.12\.2023|1 декабря 2023/.test(a) &&
           /1105|№ 1105|no. 1105/.test(a);
}

const checks = [
    ['A: заголовок кнопки — Инструкция СО 153-34.03.603-2003',
     /153-34\.03\.603-2003|инструкция со/.test(low('desktop-dark-so153-button.png'))],
    ['A: строка отмены процитирована дословно (дата + № 1105 + Минэнерго)',
     quotedCancelled('desktop-dark-so153-button.png')],
    ['A: строка КРАСНАЯ',
     /красн/.test(low('desktop-dark-so153-button.png'))],
    ['A: дефектов нет',
     !/(есть|да)[^.]{0,25}(дефект|наложен|обрезк|разъехал)/i.test(
         results['desktop-dark-so153-button.png'])],
    ['B (светлая): строка «Отменена…» на кнопке',
     quotedCancelled('desktop-light-so153-button.png')],
    ['B (светлая): строка красная',
     /красн/.test(low('desktop-light-so153-button.png'))],
    ['B (светлая): у соседних кнопок строки отмены НЕТ',
     /(нет|только|лишь|одна|одной)[^.]{0,40}(кнопк|строк)/i.test(
         low('desktop-light-so153-button.png')) ||
     /соседн[^.]{0,60}(нет|отсутств)/i.test(low('desktop-light-so153-button.png'))],
    ['B (светлая): дефектов нет',
     !/(есть|да)[^.]{0,25}(дефект|наложен|обрезк|разъехал)/i.test(
         results['desktop-light-so153-button.png'])],
    ['C (мобайл): строка отмены процитирована',
     quotedCancelled('mobile-dark-so153-button.png')],
    ['C (мобайл): строка читаема, не обрезана (отрицание учитывается)',
     // Урок Task 523/524: VLM эхо «не обрезана» — матчим только
     // утверждения о дефекте БЕЗ отрицания рядом
     !(results['mobile-dark-so153-button.png'] || '')
         .match(/.{0,18}(обрезан|не помеща|не читае)/gi) ||
     (results['mobile-dark-so153-button.png'] || '')
         .match(/.{0,18}(обрезан|не помеща|не читае)/gi)
         .every(function(s) { return /не\s|читаема|полностью/.test(s); })],
    ['C (мобайл): дефектов нет',
     !/(есть|да)[^.]{0,25}(дефект|наложен|разъехал)/i.test(
         results['mobile-dark-so153-button.png'])]
];
checks.forEach(function(c) {
    console.log((c[1] ? '  + ' : '  X ') + c[0]);
    if (c[1]) { pass++; } else { fail++; }
});
fs.writeFileSync(path.join(DIR, 'vlm-task525-out.json'),
    JSON.stringify(results, null, 2));
console.log();
console.log('ИТОГО VLM: ' + pass + ' passed, ' + fail + ' failed');
if (fail) { process.exit(1); }
