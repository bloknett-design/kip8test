def process(path, ver_line, stale_subs, tag):
    print(f'=== {tag}: {path.name} ===')
    before = path.stat().st_size
    lines = path.read_text(encoding='utf-8').split('\n')

    # 1) новая строка версии + перелинейка старой
    check(lines[2].startswith('> **Версия документа:**'), 'строка 3 — текущая версия')
    lines[2] = lines[2].replace('> **Версия документа:**', '> **Версия документа (предыдущая):**', 1)
    lines.insert(2, ver_line.rstrip('\n'))

    # 2) урезка архива версий до недели
    i, kept, dropped, drop_bytes = 3, 0, 0, 0
    out = lines[:3]
    cur_keep = None
    for ln in lines[3:]:
        if ln.startswith('> **Текущая версия кэша:**'):
            out.append('')                      # отступ перед метаданными
            out.append(TRIM_NOTE.rstrip('\n'))
            out.append(ln)
            out.extend(lines[lines.index(ln)+1:])
            break
        m = re.match(r'> \*\*Версия документа(?: \(предыдущая\))?:\*\* (\d{4}-\d{2}-\d{2})', ln)
        if m:
            cur_keep = m.group(1) >= CUTOFF
            if cur_keep:
                kept += 1; out.append(ln)
            else:
                dropped += 1; drop_bytes += len(ln)
        else:
            # продолжение/пустая строка многострочной записи
            if cur_keep is True:
                out.append(ln)
            elif cur_keep is False:
                drop_bytes += len(ln)
            # cur_keep is None — ничего до первой записи (нет такого случая)
    new_lines = out
    check(kept >= 10, f'оставлено записей истории: {kept} (>= 10)')
    check(dropped > 10, f'удалено записей старше {CUTOFF}: {dropped} ({drop_bytes//1024} КБ)')

    text = '\n'.join(new_lines)
    path.write_text(text, encoding='utf-8')

    # 3) stale-поля
    for old, new in stale_subs:
        n = text.count(old)
        check(n == 1, f'{tag} stale: «{old[:48]}…» ×{n}')
        text = text.replace(old, new)
    # страницы 95 → 97
    n = text.count('# ожидается: 95')
    check(n == 1, f'{tag}: счётчик страниц 95 ×{n}')
    text = text.replace('# ожидается: 95', '# ожидается: 97')

    # 4) функционал: неверная пометка + подраздел
    n = text.count(CJ_LINE_OLD)
    check(n == 1, f'{tag}: пометка «редактирование НЕ поддерживается» ×{n}')
    text = text.replace(CJ_LINE_OLD, CJ_LINE_NEW)
    anchor = '### Версия 2.0.0 / 3.0.0 — настраиваемый дашборд'
    n = text.count(anchor)
    check(n == 1, f'{tag}: якорь вставки подраздела ×{n}')
    text = text.replace(anchor, FUNC_BLOCK + anchor)

    path.write_text(text, encoding='utf-8')
    after = path.stat().st_size
    print(f'  размер: {before//1024} КБ → {after//1024} КБ ({(before-after)//1024} КБ сэкономлено)')

process(KT, VER_KT, STALE_KT, 'kip8test')
