"""Task 511 — «РЕГЛАМЕНТ СМЕНЫ ЧАТА» (контрольные параметры + протокол закрытия чата).

Заявка: «Предлагаю добавить в файлы проектов инструкцию с контрольными параметрами,
по которым агент чата работы с проектом будет предлагать продолжить работу над
проектом в новом чате... при согласии пользователя, агент чата автоматически должен
подготовить основные нужные файлы для работы над проектом в новом чате» (подтверждено:
«делай по твоим рекомендациям»).

Что делает (docs-only, приложение НЕ трогает):
1. Вставляет «### 7. Регламент смены чата (контрольные параметры)» в конец раздела
   «📚 Инструкция для продолжения редактирования в новых чатах» (после п.6) в промты
   ОБОИХ репо (зеркально).
2. Обновляет строку «Версия документа» -> post-Task 511 (новая строка 3);
   post-Task 510 сжимается в «(предыдущая)» ≤ 420 симв. (регламент Task 509/510).
3. Дописывает запись Task 511 в worklog.md обоих репо.
"""

import io
import sys

PROMPT_NAME = 'Системный_промт_для_приложения_КИПиА.md'

APK_ANCHOR = '- **Сборка APK:** только в `kip8` — см. отдельный раздел про APK (через Bubblewrap CLI)'

SUBSECTION = """### 7. Регламент смены чата (контрольные параметры) — Task 511

Контекст чата ограничен; при переполнении платформа подставляет авто-сводку, которая теряет
точные факты (хеши коммитов, SW-версии, счётчики тестов, статусы мок-данных, PAT-состояние).
Агент ОБЯЗАН отслеживать контрольные параметры ниже и при срабатывании любого из них
предложить пользователю продолжить работу над проектом в новом чате.

**Триггеры (любой один → предложить смену чата одной строкой-футером в конце ответа):**

1. Выполнено ≥ 5 задач в текущем чате (счёт подряд по Task ID, например 511–515).
2. Обмен ≥ 70 сообщениями в текущем чате (счётчик грубый, но достаточный сигнал).
3. Обнаружен признак сжатия контекста — агент видит, что работает из авто-сводки (маркер
   вида «This session is being continued from a previous conversation…») → предлагать
   НЕМЕДЛЕННО: потери фактов уже начались; сначала восстанови недостающее из
   worklog/промта/git, затем предлагай.
4. Подтверждён перенос/деплой в kip8 (прод проверен) — естественная чистая граница.
5. Явный запрос пользователя — в любой момент.

**Правила (защита от назойливости):**

- Предложение — футером в конце ответа; работа НЕ блокируется и не выпадает обязательным шагом.
- Не более 1 предложения на каждый сработавший триггер; при отказе пользователя — молчание
  до срабатывания НОВОГО триггера (другой пункт или новый рубеж: следующая пятая задача,
  следующий деплой и т.п.).

**Протокол закрытия чата (после согласия пользователя — «да, подготовь»):**

1. Финальная запись в worklog.md ОБОИХ репо: что сделано, что осталось/ждёт команды,
   следующий номер задачи, HEAD-коммиты обоих репо, статус PAT.
2. Актуализация строки «Версия документа» в системных промтах ОБОИХ репо: SW-версии,
   тесты X/0, незакрытые переносами задачи, СЛЕДУЮЩАЯ ЗАДАЧА.
3. Коммит + push (docs) ОБОИХ репо — «передача» и есть git push: все файлы для нового
   чата версионируются и доступны по raw-ссылкам.
4. Выдать пользователю ГОТОВУЮ стартовую команду для вставки в новый чат — какие файлы
   загрузить, PAT-статус, следующая задача. Шаблон:

```text
Продолжи работу над проектом КИПиА. Загрузи контекст (raw):
1) https://raw.githubusercontent.com/bloknett-design/kip8test/main/Системный_промт_для_приложения_КИПиА.md
2) https://raw.githubusercontent.com/bloknett-design/kip8test/main/worklog.md
3) https://raw.githubusercontent.com/bloknett-design/kip8test/main/ARCHITECTURE.md
(если задача затрагивает боевой kip8 — те же 3 файла репозитория kip8)
Следующая задача: №<N>. PAT: <жив, /home/z/.kip_pat / передай заново>.
```"""

VER_TPL = ('> **Версия документа:** 2026-10-12 (post-Task 511 — РЕГЛАМЕНТ СМЕНЫ ЧАТА '
 '(заявка: контрольные параметры, по которым агент предлагает продолжение работы над '
 'проектом в новом чате + автоподготовка основных файлов при согласии): в раздел '
 '«📚 Инструкция для продолжения редактирования в новых чатах» добавлен подраздел 7 — '
 '5 триггеров (≥5 задач в чате / ≥70 сообщений / работа из авто-сводки сжатого контекста → '
 'предложение НЕМЕДЛЕННО, сперва восстановление фактов из worklog/промта/git / '
 'подтверждён деплой в kip8 / явный запрос), правила анти-назойливости (футер, не '
 'блокирует работу, 1 предложение на триггер, при отказе — молчание до нового триггера), '
 'протокол закрытия (финальная запись worklog обоих репо → актуализация строки состояния '
 'промтов → коммит+push docs → ГОТОВАЯ стартовая команда нового чата: промт+worklog+'
 'ARCHITECTURE.md по raw-ссылкам, PAT-статус, следующая задача). Документация-only: '
 'приложение не менялось (SW {sw}, тесты {tests}). СЛЕДУЮЩАЯ ЗАДАЧА: 512.)')

PREV_TPL = ('> **Версия документа (предыдущая):** 2026-10-12 (post-Task 510 — ОПТИМИЗАЦИЯ '
 'СИСТЕМНЫХ ФАЙЛОВ (заявка «Делай все пункты»): история промта → индекс; DEPLOY/PNG/'
 'скрипты старше недели УДАЛЕНЫ (теги {tags}: git show pre-task510:<путь>); ротация '
 'worklog.md; НОВЫЙ ARCHITECTURE.md §1-§6; тесты {tests}, приложение не менялось ({sw})…)')

WL_TPL = """---
Task ID: 511
Agent: main (Super Z)
Task: Заявка (предложение, подтверждено «делай по твоим рекомендациям»): «Предлагаю добавить
      в файлы проектов инструкцию с контрольными параметрами, по которым агент чата работы
      с проектом будет предлагать продолжить работу над проектом в новом чате, для того
      чтобы со временем большой контекст чата не вносил каких либо помех в разработке, и
      при согласии пользователя, агент чата автоматически должен подготовить основные
      нужные файлы для работы над проектом в новом чате» — РЕГЛАМЕНТ СМЕНЫ ЧАТА в системные
      промты ОБОИХ репо (docs-only{mirror_note}).

Work Log:
- Обоснование: платформенная авто-сводка при переполнении контекста теряет точные факты
  (хеши коммитов, SW-версии, счётчики тестов) — подтверждено текущей сессией; ~70%
  потребности уже закрыто существующей дисциплиной (worklog/промт/DEPLOY/теги), поэтому
  внедрены ТОЛЬКО триггеры «когда предлагать» + протокол закрытия — без новых типов
  файлов (курс Task 510 на чистоту репо).
- Системный промт: НОВЫЙ подраздел «### 7. Регламент смены чата (контрольные параметры)»
  (конец раздела «📚 Инструкция для продолжения редактирования в новых чатах», после п.6):
  5 триггеров — ≥5 задач в чате / ≥70 сообщений / работа из авто-сводки (маркер «This
  session is being continued…») → предложение НЕМЕДЛЕННО + восстановление фактов из
  worklog/промта/git ДО предложения / подтверждён деплой в kip8 / явный запрос;
  анти-назойливость — футер, работа не блокируется, 1 предложение на триггер, при отказе
  молчание до НОВОГО триггера; протокол закрытия 4 шага — финальная запись worklog ОБОИХ
  репо → актуализация строки «Версия документа» промтов → коммит+push (docs) → ГОТОВАЯ
  стартовая команда нового чата (raw-ссылки: промт + worklog + ARCHITECTURE.md,
  PAT-статус, следующая задача).
- Версия документа: post-Task 511 (новая строка 3), post-Task 510 → «(предыдущая)» сжата
  до ≤ 420 симв. (регламент Task 509/510). СЛЕДУЮЩАЯ ЗАДАЧА: 512.
- Контроль: node tests/run-all.js — {tests} (docs-only, набор тестов не менялся).
  index.html / sw.js / данные НЕ тронуты.{script_note}
- Коммит docs (промт + worklog{script_files}) + push.

Stage Summary:
- «Регламент смены чата» внедрён зеркально в промты ОБОИХ репо. Приложение не менялось
  ({sw_here}, тесты {tests_here}; {other_repo}). СЛЕДУЮЩАЯ ЗАДАЧА: 512."""

REPOS = [
    {
        'root': '/home/z/my-project/kip8test',
        'sw': 'kipia-test-v730',
        'tests': '6472/0',
        'tags': 'pre-task510/v729-task506/v730-task508/v730-post509',
        'other_repo': 'kip8 — v527, 6476/0',
        'mirror_note': '',
        'script_note': '\n- Скрипт процесса: scripts/task511-update-prompt.py (вставка подраздела 7 +\n  строки версий в промты обоих репо + записи worklog, зеркально).',
        'script_files': ' + скрипт scripts/task511-update-prompt.py',
    },
    {
        'root': '/home/z/my-project/kip8',
        'sw': 'kipia-v527',
        'tests': '6476/0',
        'tags': 'pre-task510/v526-task507/v527-task509-transfer/v527-post509',
        'other_repo': 'kip8test — v730, 6472/0',
        'mirror_note': ', зеркально с kip8test',
        'script_note': '\n- Скрипт процесса — kip8test/scripts/task511-update-prompt.py (общий для обоих репо).',
        'script_files': '',
    },
]


def process(repo):
    root = repo['root']
    prompt_path = root + '/' + PROMPT_NAME
    with io.open(prompt_path, encoding='utf-8') as f:
        text = f.read()

    # --- проверки-препусловия ---
    assert text.count('### 6. Типовые задачи и их решение') == 1, 'якорь п.6 не уникален'
    assert text.count(APK_ANCHOR) == 1, 'якорь «Сборка APK» не уникален'
    assert '### 7. Регламент смены чата' not in text, 'подраздел 7 уже есть (повторный запуск?)'
    lines = text.split('\n')
    assert lines[2].startswith('> **Версия документа:** 2026-10-12 (post-Task 510'), \
        'строка 3 не post-Task 510: ' + lines[2][:80]
    assert 'СЛЕДУЮЩАЯ ЗАДАЧА: 511' in lines[2], 'в строке 3 нет «ЗАДАЧА: 511»'

    # --- 1) подраздел 7 после п.6 (якорь — последний пункт подраздела 6) ---
    text = text.replace(APK_ANCHOR, APK_ANCHOR + '\n\n' + SUBSECTION)

    # --- 2) строка версии: post-510 -> post-511 + сжатая «предыдущая» ---
    lines = text.split('\n')
    new_ver = VER_TPL.format(sw=repo['sw'], tests=repo['tests'])
    prev_ver = PREV_TPL.format(tags=repo['tags'], tests=repo['tests'], sw=repo['sw'])
    assert len(prev_ver) <= 420, '«предыдущая» длиннее лимита: %d' % len(prev_ver)
    lines[2:3] = [new_ver, prev_ver]
    text = '\n'.join(lines)

    with io.open(prompt_path, 'w', encoding='utf-8') as f:
        f.write(text)

    # --- 3) worklog: запись Task 511 ---
    wl_path = root + '/worklog.md'
    with io.open(wl_path, encoding='utf-8') as f:
        wtext = f.read()
    assert 'Task ID: 511' not in wtext, 'запись 511 уже в worklog (повторный запуск?)'
    entry = WL_TPL.format(
        mirror_note=repo['mirror_note'],
        tests=repo['tests'],
        script_note=repo['script_note'],
        script_files=repo['script_files'],
        sw_here=repo['sw'],
        tests_here=repo['tests'],
        other_repo=repo['other_repo'],
    )
    wtext = wtext.rstrip('\n') + '\n\n' + entry + '\n'
    with io.open(wl_path, 'w', encoding='utf-8') as f:
        f.write(wtext)

    # --- пост-проверки (перечитать с диска) ---
    with io.open(prompt_path, encoding='utf-8') as f:
        final = f.read()
    ok_sub = final.count('### 7. Регламент смены чата') == 1
    ok_ver = '> **Версия документа:** 2026-10-12 (post-Task 511' in final
    ok_prev = final.count('> **Версия документа (предыдущая):** 2026-10-12 (post-Task 510') == 1
    ok_fence = final.count('```') % 2 == 0  # парность код-блоков не нарушена
    with io.open(wl_path, encoding='utf-8') as f:
        wfinal = f.read()
    ok_wl = 'Task ID: 511' in wfinal and 'СЛЕДУЮЩАЯ ЗАДАЧА: 512' in wfinal
    assert all([ok_sub, ok_ver, ok_prev, ok_fence, ok_wl]), \
        (ok_sub, ok_ver, ok_prev, ok_fence, ok_wl)
    print('OK %s: подраздел 7 + версия post-511 + prev-510 (сжат) + worklog-511'
          % root.split('/')[-1])


def main():
    for repo in REPOS:
        process(repo)
    print('Task 511: оба промта и оба worklog обновлены.')


if __name__ == '__main__':
    sys.exit(main())
