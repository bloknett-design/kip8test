#!/usr/bin/env python3
# -*- coding: utf-8 -*-
# Task 488: расширение ОКОН ИСТОРИИ sw.js в тестах.
# Комментарий Task 488 (~12 строк, ~800 симв.) отодвинул якоря задач
# в шапке sw.js; дистанции от CACHE_VERSION ('kipia-test-v712'):
#   461 ~9825 (окно 9800 — ПРОВАЛ); 471 ~7263 (7000 — ПРОВАЛ);
#   472 ~6714 (6500 — ПРОВАЛ); 474 ~6341 (6000 — ПРОВАЛ);
#   473 ~6453 (6200 — ПРОВАЛ); 483 ~3322 (2500 — ПРОВАЛ);
#   484 ~2997 (2500 — ПРОВАЛ); 485 ~2607 (2100 — ПРОВАЛ);
#   486 ~1909 (1500 — ПРОВАЛ); 480 ~4205 (4000 — ПРОВАЛ);
#   478 ~4799 (4100 — ПРОВАЛ); 481 ~3961 (4000 — запас 39 < 100).
# Новые значения (запасы ~500-800):
#   461: 9800 → 10600; 471: 7000 → 8000; 472: 6500 → 7500;
#   474: 6000 → 7000; 473: 6200 → 7200; 478/479: 4100 → 5600;
#   480/481/482-окна: 4000 → 5000; 483: 2500 → 3900; 484: 2500 → 3500
#   (единая замена 2500 → 3900 — большим окнам «видимость» только
#   легче); 485: 2100 → 3100; 486: 1500 → 2400.
# ПОРЯДОК ЗАМЕН ВАЖЕН (уроки 482/486/487): СНАЧАЛА БОЛЬШИЕ исходные
# числа: 7000 → 8000 ДО 6000 → 7000 (иначе новые 7000 попадут под
# повторную замену); C-формы (мета-литералы в кавычках — тесты
# 475/481/486/482 сверяют ОКНА ДРУГИХ файлов) — тем же убывающим
# порядком ПОСЛЕ B-форм.
import glob

OWN = 'tests/test-task488.js'

sw = open('sw.js', encoding='utf-8').read()
assert "const CACHE_VERSION = 'kipia-test-v712';" in sw
assert 'Task 488' in sw

# --- B-форма: A-дистанции и срезы (реальные окна) ---
B = [
    # ПОРЯДОК: убывание исходного значения!
    ('(i - i461) < 9800', '(i - i461) < 10600'),
    ('Math.max(0, i - 9800)', 'Math.max(0, i - 10600)'),
    ('(i - i471) < 7000', '(i - i471) < 8000'),
    ('Math.max(0, i - 7000)', 'Math.max(0, i - 8000)'),
    ('(i - i472) < 6500', '(i - i472) < 7500'),
    ('Math.max(0, i - 6500)', 'Math.max(0, i - 7500)'),
    ('Math.max(0, i - 6200)', 'Math.max(0, i - 7200)'),
    ('(i - i474) < 6000', '(i - i474) < 7000'),
    ('Math.max(0, i - 6000)', 'Math.max(0, i - 7000)'),
    ('Math.max(0, i - 4100)', 'Math.max(0, i - 5600)'),
    ('Math.max(0, i - 4000)', 'Math.max(0, i - 5000)'),
    ('Math.max(0, i - 2500)', 'Math.max(0, i - 3900)'),
    ('Math.max(0, i - 2100)', 'Math.max(0, i - 3100)'),
    ('Math.max(0, i - 1500)', 'Math.max(0, i - 2400)'),
]

stats = {}
for f in sorted(glob.glob('tests/*.js')):
    if f.replace('\\', '/') == OWN:
        continue
    s = open(f, encoding='utf-8').read()
    orig = s
    for old, new in B:
        n = s.count(old)
        if n:
            s = s.replace(old, new)
            stats.setdefault(old + ' → ' + new, []).append((f, n))
    if s != orig:
        open(f, 'w', encoding='utf-8').write(s)
total_b = 0
for k, v in sorted(stats.items()):
    t = sum(n for _, n in v)
    total_b += t
    print('B: %s: %d мест в %d файлах' % (k, t, len(v)))

# --- C-форма: мета-литералы (в кавычках) в тестах 475/481/486/482 ---
C = [
    # тот же убывающий порядок!
    ("'i - 9800'", "'i - 10600'"),
    ('"i - 9800"', '"i - 10600"'),
    ("'i - 7000'", "'i - 8000'"),
    ('"i - 7000"', '"i - 8000"'),
    ("'i - 6500'", "'i - 7500'"),
    ('"i - 6500"', '"i - 7500"'),
    ("'i - 6000'", "'i - 7000'"),
    ('"i - 6000"', '"i - 7000"'),
    ("'i - 4100'", "'i - 5600'"),
    ('"i - 4100"', '"i - 5600"'),
    ("'i - 4000'", "'i - 5000'"),
    ('"i - 4000"', '"i - 5000"'),
    ("'i - 2500'", "'i - 3900'"),
    ('"i - 2500"', '"i - 3900"'),
]
stats_c = {}
for f in ['tests/test-task475.js', 'tests/test-task481.js',
          'tests/test-task486.js', 'tests/test-task482.js']:
    s = open(f, encoding='utf-8').read()
    orig = s
    for old, new in C:
        n = s.count(old)
        if n:
            s = s.replace(old, new)
            stats_c.setdefault(old + ' → ' + new, []).append((f, n))
    if s != orig:
        open(f, 'w', encoding='utf-8').write(s)
total_c = 0
for k, v in sorted(stats_c.items()):
    t = sum(n for _, n in v)
    total_c += t
    print('C: %s: %d мест в %d файлах' % (k, t, len(v)))

print('Итого: B-форм %d, C-форм %d' % (total_b, total_c))
