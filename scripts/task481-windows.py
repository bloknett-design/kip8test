import io

def patch(path, repls):
    with io.open(path, encoding='utf-8') as f:
        s = f.read()
    for old, new, cnt in repls:
        c = s.count(old)
        assert c == cnt, '%s: %r найдено %d раз (ожидалось %d)' % (path, old[:60], c, cnt)
        s = s.replace(old, new)
    with io.open(path, 'w', encoding='utf-8') as f:
        f.write(s)
    print('OK: %s (%d замен)' % (path, len(repls)))

