#!/usr/bin/env node
// scripts/task495-vlm-check.js — VLM-проверка скриншотов Task 495
// (паттерн task494-vlm-check.js; CLI `z-ai vision`).
// Ожидаем: на странице датчика температуры НЕТ блока «Тип датчика»
// (чипа) и подсказки «Шаг расчёта таблицы в градусах Цельсия»; блок
// ввода данных для расчёта таблицы (Диапазон измерения + Шаг таблицы)
// оформлен как панель с эффектом УГЛУБЛЕНИЯ (утоплена в страницу,
// рамка тоньше, внутренние тени), в отличие от панели произвольного
// расчёта над ней (выступ: яркая рамка, градиент, тень снизу).
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const DIR = '/home/z/my-project/download/kip8test-task495';

function vision(file, prompt) {
    const out = execFileSync('z-ai', [
        'vision', '-p', prompt, '-i', path.join(DIR, file)
    ], { encoding: 'utf8', timeout: 120000, stdio: ['ignore', 'pipe', 'pipe'] });
    const m = out.match(/"content":\s*"((?:[^"\\]|\\.)*)"/);
    return m ? JSON.parse('"' + m[1] + '"') : out;
}

const shots = [
    ['a-mobile-dark-rtd.png',
     'Это скриншот мобильного веб-приложения (тёмная тема, 375px), страница расчёта датчика температуры. Ответь строго по пунктам: (1) Есть ли на странице надпись «Тип датчика» или карточка/чип с названием датчика между заголовком и полями ввода? — их быть НЕ должно. (2) Есть ли мелкая серая подсказка «Шаг расчёта таблицы в градусах Цельсия»? — её быть НЕ должно. (3) Сколько панелей с полями ввода видно (счёт вместе с частично видимыми)? (4) Верхняя панель выглядит приподнятой (выступ), а блок ниже — утопленным (углубление, темнее, без яркой рамки)?'],
    ['e-mobile-dark-table-panel.png',
     'Это скриншот мобильного веб-приложения (тёмная тема, 375px), прокрутка к блоку ввода данных для расчёта таблицы: «Диапазон измерения (°C)» с полями min/max и «Шаг таблицы (°C)». Ответь строго по пунктам: (1) Этот блок оформлен как отдельная панель-«колодец»: тёмный фон, тонкая рамка, ВНУТРЕННИЕ тени (выглядит УТОПЛЕННЫМ в страницу, а не приподнятым)? (2) Поля ввода крупные (высокие), текст крупный? (3) Есть ли кнопка «Рассчитать» под блоком? (4) Есть ли внутри блока чип/карточка с названием датчика или подпись «Тип датчика»? — быть НЕ должно.'],
    ['b-mobile-dark-tc.png',
     'Это скриншот мобильного веб-приложения (тёмная тема, 375px), страница расчёта термопары ТХА (K). Ответь строго по пунктам: (1) Есть ли надпись «Тип датчика» или чип с названием датчика над полями «Диапазон измерения»? — НЕ должно быть. (2) Заголовок страницы содержит название и тип датчика? (3) Блок «Диапазон измерения / Шаг таблицы» оформлен панелью-углублением?'],
    ['c-mobile-light-rtd.png',
     'Это скриншот мобильного веб-приложения (СВЕТЛАЯ тема, 375px), страница расчёта датчика температуры. Ответь строго по пунктам: (1) Есть ли надпись «Тип датчика»? — НЕ должно быть. (2) Блок с полями «Диапазон измерения» выглядит утопленной панелью (углубление) на светлом фоне? (3) Поля крупные и читаемые? (4) Подсказки «Шаг расчёта таблицы в градусах Цельсия» нет?'],
    ['d-desktop-dark-rtd.png',
     'Это скриншот ДЕСКТОПНОЙ версии (1280px, тёмная тема), страница расчёта датчика температуры, слева колонка с панелями ввода. Ответь строго по пунктам: (1) Есть ли надпись «Тип датчика» или чип датчика в колонке слева? — НЕ должно быть. (2) Верхняя панель (Температура/Сопротивление) — с яркой рамкой-выступом, а блок ниже (Диапазон/Шаг таблицы) — утопленная панель-углубление с более тёмным фоном? (3) Кнопка «Рассчитать» отдельно под блоками?']
];

// Ожидание пункта (1) по каждому кадру:
//   'absent' — «Типа датчика»/чипа нет (ответ: нет/отсутствует;
//              VLM может ответить «Да, … нет» — «да» на вопрос
//              + «нет» про надпись);
//   'inset'  — блок-«колодец» есть (ответ: да/утоплен/inset).
const EXPECT = {
    'a-mobile-dark-rtd.png': 'absent',
    'e-mobile-dark-table-panel.png': 'inset',
    'b-mobile-dark-tc.png': 'absent',
    'c-mobile-light-rtd.png': 'absent',
    'd-desktop-dark-rtd.png': 'absent'
};

// Кэш ответов: повторный прогон не дёргает VLM (оценка по JSON)
const CACHE = path.join(DIR, 'vlm-task495-out.json');
let cache = {};
if (fs.existsSync(CACHE)) cache = JSON.parse(fs.readFileSync(CACHE, 'utf8'));

let pass = 0, fail = 0;
for (const [file, prompt] of shots) {
    if (!fs.existsSync(path.join(DIR, file))) {
        console.log('нет файла ' + file); fail++; continue;
    }
    let txt;
    if (cache[file] !== undefined) {
        txt = cache[file];
        console.log('(из кэша) === ' + file + ' ===');
    } else {
        txt = vision(file, prompt);
        cache[file] = String(txt);
        fs.writeFileSync(CACHE, JSON.stringify(cache, null, 1), 'utf8');
        console.log('=== ' + file + ' ===');
    }
    console.log(String(txt).slice(0, 2400));
    console.log('');
    const q1 = String(txt).replace(/\*/g, '');
    // VLM форматирует пункт (1) и как «(1) …», и как «1. …»
    const m1 = q1.match(/(?:\(1\)|(?:^|\n)\s*\*{0,2}1\.)\s*\*{0,2}\s*([^)]{1,80})/);
    const ans1 = m1 ? m1[1].toLowerCase() : '';
    let ok;
    if (EXPECT[file] === 'inset') {
        ok = ans1.startsWith('да') || ans1.includes('утоплен') ||
             ans1.includes('inset') || ans1.includes('колодец') ||
             ans1.includes('внутренн');
    } else {
        ok = ans1.includes('нет') || ans1.includes('отсутствует');
    }
    if (ok) pass++;
    else fail++;
    console.log('   [%s] пункт(1) (%s): %s', ok ? 'PASS' : 'FAIL',
                EXPECT[file], ans1.slice(0, 60));
}
console.log('VLM: %d passed, %d failed', pass, fail);
if (fail) process.exit(1);
