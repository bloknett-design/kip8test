#!/usr/bin/env node
// scripts/task493-vlm-check.js — VLM-проверка скриншотов Task 493
// (паттерн task492-vlm-check.js; CLI `z-ai vision`).
// Ожидаем: закреплённая на главной кнопка «Табель учёта» — КОРОТКОЕ
// имя (без «рабочего времени»), субметка «Шахматка сменного и
// дневного персонала»; заголовок страницы табеля — полное имя;
// статическая кнопка на «Документации ИОС» — тоже короткое имя.
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const DIR = '/home/z/my-project/download/kip8test-task493';

function vision(file, prompt) {
    const out = execFileSync('z-ai', [
        'vision', '-p', prompt, '-i', path.join(DIR, file)
    ], { encoding: 'utf8', timeout: 120000, stdio: ['ignore', 'pipe', 'pipe'] });
    const m = out.match(/"content":\s*"((?:[^"\\]|\\.)*)"/);
    return m ? JSON.parse('"' + m[1] + '"') : out;
}

const shots = [
    ['a-mobile-dashboard-pin.png',
     'Это скриншот мобильного веб-приложения (тёмная тема, 375px), ГЛАВНАЯ страница, сверху закреплённая пользователем кнопка-карточка. Ответь строго по пунктам: (1) Какой ТОЧНЫЙ текст крупной надписи (первая строка) у закреплённой кнопки? (2) Есть ли в этой надписи слова «рабочего времени»? — их быть НЕ должно. (3) Какой текст второй строки (подпись под надписью)? (4) Кнопка оформлена золотистым/янтарным цветом рамки или текста?'],
    ['b-mobile-work-schedule-page.png',
     'Это скриншот мобильного веб-приложения (тёмная тема, 375px), страница раздела табеля. Ответь строго по пунктам: (1) Какой ТОЧНЫЙ текст заголовка страницы вверху? (2) Заголовок содержит слова «Табель учёта рабочего времени» (полное имя)? (3) Заголовок читаем, не обрезан?'],
    ['c-mobile-docs-ios-btn.png',
     'Это скриншот мобильного веб-приложения (тёмная тема, 375px), страница «Документация ИОС». Ответь строго по пунктам: (1) Есть ли на странице кнопка-карточка с надписью «Табель учёта»? (2) Есть ли в этой надписи слова «рабочего времени»? — их быть НЕ должно. (3) Есть ли под ней подпись «Шахматка сменного и дневного персонала»?'],
    ['d-desktop-dashboard-pin.png',
     'Это скриншот ДЕСКТОПНОЙ версии (1280px), главная страница, закреплённая кнопка. Ответь строго по пунктам: (1) Какой ТОЧНЫЙ текст крупной надписи у закреплённой кнопки «Табель…»? (2) Есть ли в ней слова «рабочего времени»? — их быть НЕ должно. (3) Кнопка видна полностью, не обрезана?']
];

let pass = 0, fail = 0;
for (const [file, prompt] of shots) {
    if (!fs.existsSync(path.join(DIR, file))) {
        console.log('нет файла ' + file); fail++; continue;
    }
    const txt = vision(file, prompt);
    console.log('=== ' + file + ' ===');
    console.log(String(txt).slice(0, 2200));
    console.log('');
    if (/Табель учёта/i.test(txt)) pass++;
    else fail++;
}
console.log('VLM: %d passed, %d failed', pass, fail);
if (fail) process.exit(1);
