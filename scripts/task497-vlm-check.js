#!/usr/bin/env node
// scripts/task497-vlm-check.js — VLM-проверка скриншотов Task 497
// (паттерн task495/496-vlm-check.js; CLI `z-ai vision`).
// Заявка (баг): при первом открытии раздела «Расходомеры хозрасчётные»
// с избранным показывалось «Нет избранных расходомеров», хотя счётчик
// внизу показывал число. Фикс: избранное рендерится из кэша ДО ответа
// сервера. VLM проверяет кадры browser-check:
//   a — ДО ответа сервера: 2 карточки избранного (кэш-показания 111,11),
//       вкладка «Избранные» активна, счётчик 2, заглушки НЕТ;
//   b — ПОСЛЕ ответа: те же 2 карточки, показания обновлены (999,99);
//   c — без кэша: «Загрузка данных…» (НЕ «Нет избранных…»);
//   d — без избранного: заглушка «Нет избранных расходомеров» (как прежде).
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const DIR = '/home/z/my-project/download/kip8test-task497';

function vision(file, prompt) {
    const out = execFileSync('z-ai', [
        'vision', '-p', prompt, '-i', path.join(DIR, file)
    ], { encoding: 'utf8', timeout: 120000, stdio: ['ignore', 'pipe', 'pipe'] });
    const m = out.match(/"content":\s*"((?:[^"\\]|\\.)*)"/);
    return m ? JSON.parse('"' + m[1] + '"') : out;
}

const shots = [
    ['a-fav-instant-cache.png',
     'Это скриншот мобильного веб-приложения (тёмная тема, 375px), раздел «Расходомеры хозрасчётные», вкладка «Избранные», снимок сделан ДО ответа сервера (данные из локального кэша). Ответь ПО ПУНКТАМ, каждый ответ — полной фразой с числами/цитатами из скриншота: (1) Сколько карточек расходомеров видно в списке? (2) Какое показание видно на первой карточке и на второй (числа)? (3) Есть ли на экране текст «Нет избранных расходомеров»? (4) Внизу бар вкладок «Все»/«Избранные»: вкладка «Избранные» подсвечена (активна) и рядом с ней цифра 2? (5) Есть ли ОБРЫВКИ графики, шум или артефакты вёрстки? (Лёгкая однородная фоновая текстура-подложка всего приложения — НЕ дефект, не путать.)'],
    ['b-fav-server-refreshed.png',
     'Это скриншот мобильного веб-приложения (тёмная тема, 375px), раздел «Расходомеры хозрасчётные», вкладка «Избранные», снимок ПОСЛЕ ответа сервера. Ответь ПО ПУНКТАМ, каждый ответ — полной фразой: (1) Сколько карточек расходомеров видно в списке? (2) Какие показания видны на карточках (числа, обновленные серверные данные)? (3) Есть ли на экране «Загрузка данных» или «Нет избранных расходомеров»? (4) Внизу бар вкладок «Все»/«Избранные»: вкладка «Избранные» активна? (5) Есть ли ОБРЫВКИ графики, шум или артефакты вёрстки? (Лёгкая однородная фоновая текстура-подложка — НЕ дефект.)'],
    ['c-no-cache-loading.png',
     'Это скриншот мобильного веб-приложения (тёмная тема, 375px), раздел «Расходомеры хозрасчётные», вкладка «Избранные», локальный кэш ПУСТ, сервер ещё не ответил. Ответь строго по пунктам: (1) Виден ли текст «Загрузка данных…»? (2) Есть ли на экране текст «Нет избранных расходомеров»? (3) Внизу бар вкладок «Все»/«Избранные» на месте? (4) Дефекты вёрстки есть?'],
    ['d-no-fav-empty-stub.png',
     'Это скриншот мобильного веб-приложения (тёмная тема, 375px), раздел «Расходомеры хозрасчётные», пользователь НЕ добавлял избранное и переключился на вкладку «Избранные». Ответь строго по пунктам: (1) Видна ли заглушка «Нет избранных расходомеров» с подсказкой «Перейдите во вкладку «Все» и нажмите ☆ на карточке»? (2) Заглушка выглядит аккуратно (иконка-звёздочка, центрирование)? (3) Дефекты вёрстки есть?']
];

// Ожидание по каждому кадру:
//   'cards'   — карточки/показания видны, заглушек нет;
//   'loading' — «Загрузка данных…» видна, «Нет избранных» НЕТ;
//   'stub'    — заглушка «Нет избранных…» видна (это правильное
//               поведение при ПУСТОМ избранном).
const EXPECT = {
    'a-fav-instant-cache.png': 'cards',
    'b-fav-server-refreshed.png': 'cards',
    'c-no-cache-loading.png': 'loading',
    'd-no-fav-empty-stub.png': 'stub'
};

// Кэш ответов: повторный прогон не дёргает VLM
const CACHE = path.join(DIR, 'vlm-task497-out.json');
let cache = {};
if (fs.existsSync(CACHE)) cache = JSON.parse(fs.readFileSync(CACHE, 'utf8'));

let pass = 0, fail = 0;
for (const [file, prompt] of shots) {
    if (!fs.existsSync(path.join(DIR, file))) {
        console.log('нет файла ' + file); fail++; continue;
    }
    let txt;
    if (cache[file] !== undefined) {
        txt = cache[file];
        console.log('(из кэша) === ' + file + ' ===');
    } else {
        txt = vision(file, prompt);
        cache[file] = String(txt);
        fs.writeFileSync(CACHE, JSON.stringify(cache, null, 1), 'utf8');
        console.log('=== ' + file + ' ===');
    }
    console.log(String(txt).slice(0, 2400));
    console.log('---');

    // Оценка ПО СМЫСЛУ (уроки Task 495/496: «Да, … нет» — понимать
    // отрицание; скоринг построчно). Строка-«дефект» — упоминание
    // дефекта БЕЗ отрицания. УРОК Task 497: \b в JS НЕ работает с
    // кириллицей (буквы ≠ \w) — «Дефектов вёрстки нет.» не
    // распознавалось отрицанием; вместо «нет\b» — «нет(?![а-яё])».
    const s = String(txt).toLowerCase();
    const lines = s.split(/[\n;]+/).filter(x => x.trim());
    let defectClaim = false;
    for (const ln of lines) {
        if (/дефект|наложени|обрез|разъеха|слома|нечитаем|артефакт|шум/.test(ln) &&
            !/не\s|нет(?![а-яё])|без\s|отсутств|н[её]\s/.test(ln)) {
            defectClaim = true;
        }
    }
    // строка-«заглушка» (для кадров, где её быть НЕ должно)
    let stubClaim = false;
    for (const ln of lines) {
        if (/нет избранных/.test(ln) &&
            !/не\s|нет(?![а-яё])|отсутств/.test(ln)) {
            stubClaim = true;
        }
    }
    let ok = false;
    // Разбор ответа ПО ВОПРОСАМ: строка «(N) ...» — ответ на вопрос N
    // (терпимо к лаконичным «(2) Да» — урок Task 497).
    const q = {};
    for (const ln of lines) {
        const m = ln.match(/^\(?\((\d)\)/) || ln.match(/^\((\d)\)/);
        if (m) q[m[1]] = ln;
    }
    const numVals = /111,11|333,33|999,99|777,77/.test(s);
    const q2yes = q['2'] && /да|111,11|333,33/.test(q['2']);
    const q3noStub = q['3'] && /нет|отсутств/.test(q['3']);
    const q5noDefect = q['5'] && /нет|отсутств|не наблюда/.test(q['5']);
    const yesCount = (s.match(
        /(?:^|[\s(«"*.—\-])(?:да[,.:;)!\s]|видн\w*|виде\w*|карточк\w*|на месте|читаем\w*|корректн\w*|аккуратн\w*)/g
    ) || []).length;
    if (EXPECT[file] === 'cards') {
        // карточки видны + значения (числом или «да» на вопрос 2) +
        // заглушки нет (вопрос 3) + область чистая (вопрос 5)
        ok = (numVals || q2yes) && q3noStub && q5noDefect &&
             !stubClaim && !defectClaim;
    } else if (EXPECT[file] === 'loading') {
        const loading = /загрузка данных/.test(s);
        ok = loading && !stubClaim && !defectClaim;
    } else if (EXPECT[file] === 'stub') {
        // здесь заглушка — это ПРАВИЛЬНО. УРОК Task 497: текст самой
        // заглушки «Нет избранных…» содержит «нет » — простое
        // отрицание его бы ложно гасило; проверяем УТВЕРЖДЕНИЕ
        // видимости («видна»/«да») БЕЗ отрицания видимости.
        const stubVisible = lines.some(ln =>
            /нет избранных/.test(ln) &&
            /видн|отображ|присутств|^\(?\(\d\)\s*\*?\*?да/.test(ln) &&
            !/не\s+видн|не\s+отображ|отсутств|нет\s+на\s+экране|не\s+наблюда/.test(ln));
        ok = stubVisible && !defectClaim;
    }
    if (ok) { pass++; } else { fail++; }
    console.log((ok ? '  + ' : '  X ') + file + ': ' + EXPECT[file] +
        (defectClaim ? ' [дефект-строка!]' : '') +
        (stubClaim && EXPECT[file] !== 'stub' ? ' [заглушка-строка!]' : ''));
}

console.log('ИТОГ VLM Task 497: ' + pass + ' passed, ' + fail + ' failed');
process.exit(fail === 0 ? 0 : 1);
