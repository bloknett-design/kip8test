const CACHE = path.join(DIR, 'vlm-task498-out.json');
let cache = {};
if (fs.existsSync(CACHE)) cache = JSON.parse(fs.readFileSync(CACHE, 'utf8'));

function score(txt, file) {
    // по-вопросный разбор ПО СМЫСЛУ (урок 497: «Да, … нет» — по смыслу):
    // позитивные вопросы — «да»; вопрос о дефектах — «нет»/«не наблюдается».
    const t = String(txt);
    let ok = true;
    const qs = t.split(/\(\d\)|(?=^\d\.\s)/m).map(x => x.trim()).filter(x => x);
    if (qs.length >= 3) {
        for (const q of qs) {
            const low = q.toLowerCase();
            const isDefectQ = /дефект/i.test(q);
            const negated = /не наблюд|не содержит|отсутств|нет\b|ничего|не замечен|не обнаруж/i.test(low.slice(0, 60));
            const hasYes = /(^|[^а-яё])да[,. ]/i.test(low) || /да\b/i.test(low.slice(0, 20));
            if (isDefectQ) {
                // «нет/не наблюдается дефектов» — хорошо; «да, есть дефект» — плохо
                if (negated && !/есть .*дефект|обнаружен дефект/i.test(low)) { /* ок */ }
                else if (/^да[,.]?\s*(есть|видны?|обнаруж)/i.test(low.trim())) { ok = false; }
            } else {
                if (!hasYes && /(^|[^а-яё])(нет|не видн|неверно|отсутств)/i.test(low)) { ok = false; }
            }
        }
    } else {
        // короткий ответ: явные дефекты без негации
        if (/(есть|видны?|присутству)\D{0,40}дефект/i.test(t)) ok = false;
    }
    return ok;
}

let pass = 0, fail = 0;
const results = {};
for (const [file, prompt] of shots) {
    if (!fs.existsSync(path.join(DIR, file))) {
        console.log('нет файла ' + file); fail++; continue;
    }
    let txt;
    if (cache[file] !== undefined) {
        txt = cache[file];
    } else {
        try {
            txt = vision(file, prompt);
        } catch (e) {
            console.log('ОШИБКА VLM ' + file + ': ' + e.message);
            txt = '(ошибка)';
        }
        cache[file] = txt;
        fs.writeFileSync(CACHE, JSON.stringify(cache, null, 1), 'utf8');
    }
    const ok = score(txt, file);
    results[file] = ok ? 'PASS' : 'FAIL';
    if (ok) pass++; else fail++;
    console.log('=== ' + file + ' === ' + (ok ? 'PASS' : 'FAIL'));
    console.log(String(txt).slice(0, 600).replace(/\n+/g, ' | '));
    console.log('');
}

console.log('ИТОГО VLM: %d PASS, %d FAIL', pass, fail);
process.exit(fail ? 1 : 0);
