#!/usr/bin/env node
// scripts/task494-vlm-check.js — VLM-проверка скриншотов Task 494
// (паттерн task493-vlm-check.js; CLI `z-ai vision`).
// Ожидаем: на странице датчика температуры панель произвольного
// расчёта БЕЗ заголовка «Расчёт произвольных значений» и БЕЗ подсказки
// «Введите значение в любое поле…»; панель с рамкой-выступом
// (градиент + тень); ДВА крупных поля ввода (Температура и
// Сопротивление/Термо-ЭДС) с крупным ярким текстом.
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const DIR = '/home/z/my-project/download/kip8test-task494';

function vision(file, prompt) {
    const out = execFileSync('z-ai', [
        'vision', '-p', prompt, '-i', path.join(DIR, file)
    ], { encoding: 'utf8', timeout: 120000, stdio: ['ignore', 'pipe', 'pipe'] });
    const m = out.match(/"content":\s*"((?:[^"\\]|\\.)*)"/);
    return m ? JSON.parse('"' + m[1] + '"') : out;
}

const shots = [
    ['a-mobile-dark-rtd.png',
     'Это скриншот мобильного веб-приложения (тёмная тема, 375px), страница расчёта датчика температуры 50М. Сверху страницы есть панель с ДВУМЯ полями ввода (Температура и Сопротивление). Ответь строго по пунктам: (1) Есть ли НАД полями заголовок «Расчёт произвольных значений»? — его быть НЕ должно. (2) Есть ли мелкая серая подсказка «Введите значение в любое поле — другое рассчитается автоматически»? — её быть НЕ должно. (3) Выглядит ли панель как «приподнятая» карточка: заметная рамка, лёгкий градиент фона, тень снизу? (4) Поля ввода крупные, текст в них крупный и хорошо читаемый? (5) Какие подписи у полей?'],
    ['b-mobile-dark-tc.png',
     'Это скриншот мобильного веб-приложения (тёмная тема, 375px), страница расчёта термопары ТХА (K). Ответь строго по пунктам: (1) Есть ли заголовок «Расчёт произвольных значений»? — НЕ должно быть. (2) Какая подпись у второго поля ввода — «Термо-ЭДС E(t), мВ»? (3) Есть ли рассчитанное значение (число) в одном из полей? (4) Поля крупные и читаемые?'],
    ['c-mobile-light-rtd.png',
     'Это скриншот мобильного веб-приложения (СВЕТЛАЯ тема, 375px), страница расчёта датчика температуры. Ответь строго по пунктам: (1) Есть ли заголовок «Расчёт произвольных значений»? — НЕ должно быть. (2) Панель с полями оформлена заметной рамкой и выглядит приподнятой? (3) Тёмный текст на светлых полях, крупный шрифт? (4) Сколько полей ввода в панели?'],
    ['d-desktop-dark-rtd.png',
     'Это скриншот ДЕСКТОПНОЙ версии (1280px, тёмная тема), страница расчёта датчика температуры, слева колонка с панелью из двух полей. Ответь строго по пунктам: (1) Есть ли заголовок «Расчёт произвольных значений»? — НЕ должно быть. (2) Панель с рамкой-выступом (градиент + тень)? (3) Поля ввода крупные (выше обычных полей формы ниже)? (4) Список полей в панели?']
];

let pass = 0, fail = 0;
for (const [file, prompt] of shots) {
    if (!fs.existsSync(path.join(DIR, file))) {
        console.log('нет файла ' + file); fail++; continue;
    }
    const txt = vision(file, prompt);
    console.log('=== ' + file + ' ===');
    console.log(String(txt).slice(0, 2200));
    console.log('');
    // Пункт (1) каждого промпта — «Есть ли заголовок …?»;
    // корректный ответ — «Нет» (заголовок/подсказка удалены).
    // VLM цитирует фразу из вопроса в ответе «Нет, …» — простое
    // вхождение фразы НЕ является дефектом; проверяем пункт (1).
    const q1 = String(txt).replace(/\*/g, '');
    const m1 = q1.match(/\(1\)\s*([^)]{1,60})/);
    const ans1 = m1 ? m1[1].toLowerCase() : '';
    const ok = ans1.startsWith('нет') || ans1.includes('отсутствует') ||
               ans1.includes('нет,') || ans1.includes('нет.');
    if (ok) pass++;
    else fail++;
    console.log('   [%s] пункт(1): %s', ok ? 'PASS' : 'FAIL', ans1.slice(0, 60));
}
console.log('VLM: %d passed, %d failed', pass, fail);
if (fail) process.exit(1);
