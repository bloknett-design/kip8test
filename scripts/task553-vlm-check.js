#!/usr/bin/env node
// scripts/task553-vlm-check.js — VLM-проверка скриншотов Task 553
// (паттерн task522-vlm-check.js; CLI `z-ai vision`).
// Заявка: в блоке «Повторные инструктажи и периодическая проверка
// знаний» карточки работника (страница «Работники») — отображение
// примечания записи («комментарий» листа «Инструктажи», столбец H):
// «тема · дата · «примечание»», курсив, чуть тише текста строки.
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const DIR = '/home/z/my-project/download/kip8test-task553';

function vision(file, prompt) {
    const out = execFileSync('z-ai', [
        'vision', '-p', prompt, '-i', path.join(DIR, file)
    ], { encoding: 'utf8', timeout: 120000, stdio: ['ignore', 'pipe', 'pipe'] });
    const m = out.match(/"content":\s*"((?:[^"\\]|\\.)*)"/);
    return m ? JSON.parse('"' + m[1] + '"') : out;
}

const NOTE_DARK = 'Это страница «Работники» раздела «Табель учёта рабочего времени» (тёмная тема), карточка работника Иванова. Должно быть окно блока «Повторные инструктажи и периодическая проверка знаний · 2026». Ответь строго по пунктам: (1) Заголовок этого блока виден? (2) В строке «Повторный инструктаж по рабочим инструкциям ОТ · 15.03.2026» после даты идёт примечание в кавычках-ёлочках «протокол № 12, ведёт Иванов А.А.», набранное КУРСИВОМ и чуть тусклее основного текста? (3) Строка «Внеплановый инструктаж после аварии на ХВО-2 · 02.09.2026» тоже несёт примечание «по предписанию № 4-ОТ»? (4) Строка «Периодическая проверка знаний … · 20.05.2026» НЕ содержит примечания в ёлочках? (5) Строки аккуратные: ничего не наложено, не обрезано, кнопки ✓/✎/✕ на своих местах?';
const NOTE_LIGHT = 'Это та же страница «Работники» в СВЕТЛОЙ теме, карточка Иванова, блок «Повторные инструктажи и периодическая проверка знаний · 2026». Ответь строго по пунктам: (1) Примечание «протокол № 12, ведёт Иванов А.А.» после даты 15.03.2026 видно и читаемо на светлом фоне? (2) Оно курсивом? (3) Есть ли визуальные дефекты (наложение текста, обрезка, разъехавшаяся вёрстка)?';
const NOTE_023 = 'Это карточка работника Петрова на странице «Работники» (тёмная тема). Блок «Повторные инструктажи и периодическая проверка знаний · 2026»: строка «Периодическая проверка знаний … в электроустановках до 1000 В · 10.02.2026». Ответь строго по пунктам: (1) После даты видно примечание «комиссия в Ростехнадзоре, ticket РТН-8» в ёлочках? (2) Строка с длинным названием аккуратно переносится/помещается, ничего не обрезано? (3) Визуальные дефекты есть?';

const shots = [
    ['01-workers-017-instr-note-dark.png', NOTE_DARK],
    ['02-workers-023-note-dark.png', NOTE_023],
    ['03-workers-017-instr-note-light.png', NOTE_LIGHT]
];

const results = {};
shots.forEach(function(pair) {
    const txt = vision(pair[0], pair[1]);
    results[pair[0]] = txt;
    console.log('=== ' + pair[0] + ' ===');
    console.log(txt.slice(0, 800));
});

function low(f) { return String(results[f] || '').toLowerCase(); }
const checks = [
    ['A: тёмная — заголовок блока виден',
     /повторн|заголовок.*(виден|есть)|(1).*да/.test(low('01-workers-017-instr-note-dark.png'))],
    ['A: тёмная — примечание 15.03 курсивом в ёлочках',
     /протокол № 12/.test(low('01-workers-017-instr-note-dark.png')) &&
     (/курсив/.test(low('01-workers-017-instr-note-dark.png')))],
    ['A: тёмная — «вне списка» с предписанием',
     low('01-workers-017-instr-note-dark.png').indexOf('предписан') !== -1],
    ['A: тёмная — пустое примечание не показано',
     /примечани[ея][^.]{0,40}(нет|отсутств|не содержит)|(нет|отсутств|без)[^.]{0,40}примечани/.test(
         low('01-workers-017-instr-note-dark.png'))],
    ['D: Петров — примечание Ростехнадзора',
     low('02-workers-023-note-dark.png').indexOf('ростехнадзор') !== -1],
    ['E: светлая — примечание читаемо',
     low('03-workers-017-instr-note-light.png').indexOf('протокол № 12') !== -1],
    ['санитар: affirmed визуальные дефекты (все кадры)',
     shots.every(function(p) {
         return !/(есть|присутствуют?)[^.]{0,40}(дефект|наложен|обрезк|перекрыв)/i.test(
             results[p[0]] || '');
     })]
];

let pass = 0, fail = 0;
checks.forEach(function(c) {
    const ok = !!c[1];
    console.log((ok ? '  + ' : '  X ') + c[0]);
    ok ? pass++ : fail++;
});

fs.writeFileSync(path.join(DIR, 'vlm-task553-out.json'),
    JSON.stringify(results, null, 2), 'utf8');
console.log('\nИТОГО VLM: ' + pass + '/' + (pass + fail) + ', FAIL=' + fail);
process.exit(fail ? 1 : 0);
