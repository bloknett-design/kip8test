#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Task 495 — kip8test: очистка литералов из комментариев (урок Task 488:
срезы тестов ловят литералы в комментариях; удаляемые строки — «Тип
датчика», «Шаг расчёта таблицы в градусах Цельсия», id чипа, классы чипа —
не должны встречаться в index.html ВООБЩЕ, включая комментарии)."""
import io
import sys

ROOT = '/home/z/my-project/kip8test'
OK = True


def rep(path, pairs):
    global OK
    src = io.open(path, encoding='utf-8').read()
    for old, new, cnt in pairs:
        n = src.count(old)
        if n != cnt:
            print('FAIL: %r найдено %d (ожидалось %d)' % (old[:60], n, cnt))
            OK = False
            continue
        src = src.replace(old, new)
    io.open(path, 'w', encoding='utf-8').write(src)
    print('OK: %s' % path)


rep(ROOT + '/index.html', [
    # HTML-комментарий над новой панелью
    ('                         поле «Тип датчика» (чип tempSensorViewChip) и тексты\n'
     '                         «Тип датчика» / «Шаг расчёта таблицы в градусах\n'
     '                         Цельсия» УДАЛЕНЫ по заявке; блок оформлен как панель\n',
     '                         поле типа датчика (чип) и его подпись, а также\n'
     '                         подсказка про шаг пересчёта удалены по заявке;\n'
     '                         блок оформлен как панель\n', 1),
    # CSS-комментарий (снятые правила чипа)
    ('    /* Task 372: чип выбранного датчика — Task 495: чип\n'
     '       tempSensorViewChip и текст «Тип датчика» удалены из блока\n'
     '       ввода (тип датчика показывает заголовок страницы); правила\n'
     '       .ts-view-chip/-name/-meta сняты как неиспользуемые. */\n',
     '    /* Task 372: чип выбранного датчика — Task 495: чип удалён из\n'
     '       блока ввода (тип датчика показывает заголовок страницы);\n'
     '       CSS-правила чипа сняты как неиспользуемые. */\n', 1),
    # JS-комментарий в openTempSensor
    ('        // Task 495: чип «Тип датчика» (tempSensorViewChip) удалён из\n'
     '        // блока ввода — тип датчика виден в заголовке страницы\n',
     '        // Task 495: чип типа датчика удалён из блока ввода — тип\n'
     '        // датчика виден в заголовке страницы\n', 1),
])

rep(ROOT + '/sw.js', [
    ('// Task 495: «Датчики температуры» — блок ввода данных расчёта\n'
     '// таблицы: поле «Тип датчика» (чип) и тексты «Тип датчика» / «Шаг\n'
     '// расчёта таблицы в градусах Цельсия» удалены; блок оформлен как\n'
     '// панель произвольного расчёта, но с эффектом УГЛУБЛЕНИЯ\n'
     '// (ts-calc-inset). Клиент-only.\n',
     '// Task 495: «Датчики температуры» — блок ввода данных расчёта\n'
     '// таблицы: поле типа датчика (чип) с подписью и подсказка про шаг\n'
     '// пересчёта удалены; блок оформлен как панель произвольного\n'
     '// расчёта, но с эффектом УГЛУБЛЕНИЯ (ts-calc-inset). Клиент-only.\n', 1),
])

# --- Контроли: литералов в index.html нет ВООБЩЕ ---------------------
idx = io.open(ROOT + '/index.html', encoding='utf-8').read()
for gone in ['Тип датчика', 'Шаг расчёта таблицы в градусах Цельсия',
             'tempSensorViewChip', 'ts-view-chip']:
    n = idx.count(gone)
    if n:
        print('FAIL: в index.html осталось %r x%d' % (gone, n))
        OK = False
    else:
        print('Контроль: %r отсутствует' % gone)

sw = io.open(ROOT + '/sw.js', encoding='utf-8').read()
for gone in ['Тип датчика', 'Шаг расчёта таблицы в градусах Цельсия']:
    n = sw.count(gone)
    if n:
        print('FAIL: в sw.js осталось %r x%d' % (gone, n))
        OK = False
    else:
        print('Контроль: sw.js без %r' % gone)

print('RESULT: %s' % ('OK' if OK else 'FAIL'))
sys.exit(0 if OK else 1)
