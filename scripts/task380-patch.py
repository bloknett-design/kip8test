#      долгое нажатие больше НЕ выделяет текст — системный попап
#      «Копировать/Поделиться/Поиск в Google» не появляется. ДЕСКТОП
#      не тронут — выделение мышью работает как прежде.
# Правки по якорям (уникальность проверяется), каждая с меткой.
import sys, io

PATH = 'index.html'
src = io.open(PATH, encoding='utf-8').read()
orig = src
edits = []

def edit(old, new, label):
    global src
    i = src.find(old)
    if i == -1:
        print('FAIL not found: ' + label); sys.exit(1)
    if src.find(old, i + 1) != -1:
        print('FAIL dup: ' + label); sys.exit(1)
    src = src[:i] + new + src[i + len(old):]
    edits.append(label)

# ============================================================
# ЧАСТЬ 1. ОКНО «МЕРОПРИЯТИЯ»: фон строк по сроку
# ============================================================

