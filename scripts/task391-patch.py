def main():
    src = open(INDEX, encoding='utf-8').read()
    n_ok = 0
    for i, (old, new) in enumerate(REPLS, 1):
        cnt = src.count(old)
        if cnt != 1:
            print('ОШИБКА: якорь #%d найден %d раз (ожидался 1)' % (i, cnt))
            sys.exit(1)
        if old == new:
            print('ОШИБКА: правка #%d пустая' % i)
            sys.exit(1)
        src = src.replace(old, new)
        n_ok += 1
        print('правка #%d: OK' % i)

    # Контроль: старых формулировок в живом коде больше нет
    # (точки с запятой в разбивке, двоеточия после «14» / «момент»)
    for bad in ['Работников по штату 14: ',
                'Работников на текущий момент: ',
                '2 мастера; 7 дневных; 5 сменных.']:
        if bad in src:
            print('ОШИБКА: старая формулировка осталась: %r' % bad)
            sys.exit(1)

    open(INDEX, 'w', encoding='utf-8').write(src)
    print('index.html: %d/%d правок применено' % (n_ok, len(REPLS)))


if __name__ == '__main__':
    main()
